# tsasm: tree-sitter style GLR parser runtime, x86-64 (GNU as, intel syntax), any grammar without an external scanner
#
# Exports (System V AMD64):
#   TsasmParser *tsasm_parser_new(void), void tsasm_parser_free(TsasmParser *),
#   void tsasm_parser_set_memory_limit(TsasmParser *, uint64_t), void tsasm_parser_set_retain(TsasmParser *, uint64_t)
#   int64_t tsasm_parse(TsasmParser *p, const TsasmLanguage *lang, const uint8_t *src, uint64_t len,
#                       const TsasmNode **nodes)
#   const char *tsasm_language_symbol_name(const TsasmLanguage *, uint16_t),
#   uint32_t tsasm_language_symbol_count(const TsasmLanguage *)
# Grammar tables and lexers live in per-grammar objects generated by gen/gen.py.
#
# Internal convention: r15 = the caller's TsasmParser for the whole parse (callee-saved, never
# modified inside). There is no writable static data: a call touches only its own context.
# Internal functions follow SysV (rbx, rbp, r12-r15 preserved). Grow helpers preserve ALL
# registers except flags, so hot paths can call them without spilling.
#
# Data model:
#   Tree node (24 bytes): u16 symbol, u8 production_id, u8 extra, u32 start, u32 end,
#                         u32 child_count, u32 child_index (into kids[]), i32 dynamic_precedence
#   Stack node (24 bytes): C tree-sitter's graph-structured stack node: u16 state, u8 link count,
#                         u8 mark, i32 dynamic_precedence, link 0 (u32 node, u32 tree), u32 position,
#                         u32 extension block (links 1..7, 64 bytes each); a free node's link 0
#                         is the next free node
#   Head (8 bytes): u32 stack node, u32 dead (C's paused or halted; there is no error recovery)

	.intel_syntax noprefix

	.set C_NODES, 0
	.set C_NN, 8
	.set C_NCAP, 12
	.set C_KIDS, 16
	.set C_NK, 24
	.set C_KCAP, 28
	.set C_SRC, 32
	.set C_END, 40
	.set C_NH, 48                       # stack heads (versions), dead ones included until condense
	.set C_FINISHED, 52
	.set C_LASTPOS, 56
	.set C_TOKVALID, 60
	.set C_TSYM, 64
	.set C_TSTART, 68
	.set C_TEND, 72
	.set C_TPOS, 76
	.set C_TKW, 80
	.set C_TPSTATE, 84
	.set C_OUT, 88
	.set C_OUTCAP, 100
	.set C_ESTK, 104
	.set C_ESTKCAP, 116
	.set C_SAVEDRSP, 120
	.set C_STEPS, 128
	.set C_NODELIM, 136
	.set C_MEMUSED, 144
	.set C_MEMLIMIT, 152
	.set C_SFREE, 160                   # free stack nodes, linked through SN_L0 (0: none)
	.set C_XFREE, 164                   # free extension blocks, linked through XB_NEXT
	.set C_RESULT, 168
	.set C_NI, 176                      # live pop iterators
	.set C_NAVAIL, 184                  # min(node capacity, node budget): ALLOC_NODE's bound
	.set C_LANG, 192                    # copy of the TsasmLanguage descriptor for this parse
	.set C_SN, 320                      # stack nodes: ptr, u32 high-water mark, u32 capacity
	.set C_SNN, 328
	.set C_SNCAP, 332
	.set C_XB, 336                      # extension blocks: ptr, u32 high-water mark, u32 capacity
	.set C_XN, 344
	.set C_XBCAP, 348
	.set C_HEADS, 352
	.set C_HCAP, 364
	.set C_SLICES, 368                  # pop results: u32 version, u32 offset, u32 length (in C_SLK)
	.set C_NSL, 376
	.set C_SLCAP, 380
	.set C_CELLS, 384                   # pop iterators' subtree lists: u32 tree, u32 previous cell
	.set C_NCELL, 392
	.set C_CELLCAP, 396
	.set C_SLK, 400                     # slices' subtrees, bottom first (u32 tree)
	.set C_NSLK, 408
	.set C_SLKCAP, 412
	.set C_RETAIN, 416                  # u64 bytes of buffers kept between parses
	.set C_ITERS, 448                   # pop iterators: u32 stack node, u32 count, u32 cell, pad
	.set MAXITERS, 64                   # C's MAX_ITERATOR_COUNT
	.set C_SIZE, C_ITERS + MAXITERS * 16

# TsasmLanguage descriptor, emitted per grammar by gen/gen.py
	.set L_PARSE_TABLE, 0               # u16 [states][nsym] -> action index or goto state
	.set L_ACTIONS, 8                   # u64 action words, header word first
	.set L_LEX_STATE, 16                # u16 [states] lex mode
	.set L_RESERVED_SET, 24             # u8 [states] reserved word set id
	.set L_RESERVED_BITS, 32            # u64 [sets][rwords] token bitsets
	.set L_SYMBOL_FLAGS, 40             # u8 [total syms] bit0 visible, bit1 named
	.set L_PUBLIC_SYMBOL, 48            # u16 [total syms]
	.set L_ALIAS_SEQ, 56                # u16 [productions][16]
	.set L_SYMBOL_NAMES, 64             # char * [total syms]
	.set L_LEX_MAIN, 72                 # lexer entry (register contract in gen.py)
	.set L_LEX_KEYWORD, 80              # keyword lexer entry, 0 if none
	.set L_NSYM, 88                     # u32 symbol count (parse table row length)
	.set L_TOTAL_SYMS, 92               # u32 symbols + aliases
	.set L_WORD, 96                     # u32 keyword capture token, 0 if none
	.set L_RWORDS, 100                  # u32 qwords per reserved word set
	.set L_SYMBOL_OUT, 112              # u32 [total syms] public symbol | named << 16 | visible << 31
	.set L_SIZE, 128

	.set ERR_SYNTAX, -1
	.set ERR_LIMIT, -3
	.set ERR_NOMEM, -4
	.set DEFAULT_MEMLIMIT, 1 << 30
# Between parses a parser keeps at most C_RETAIN bytes of buffers (tsasm_parser_set_retain): a
# parse that grew more gives its working buffers back before it returns. Memory handed back is
# zeroed by the kernel when the next big parse faults it in, which is the cost of a low setting.
# GOROOT, 20 threads (test/mtspeed): 32 MiB keeps full speed with 30% less peak memory than
# keeping everything; 8 MiB saves 45% but parses 20-30% slower while threads share the memory bus.
	.set DEFAULT_RETAIN, 32 << 20
	.set MAP_MIN, 128 << 10             # buffers this big are mmapped (huge pages advised), so
	                                    # freeing them returns memory whatever malloc's thresholds

	.set MAXLINKS, 8                    # C's MAX_LINK_COUNT
	.set MAXVERSIONS, 6                 # C's MAX_VERSION_COUNT
	.set MAXSLICEVER, 10                # MAX_VERSION_COUNT + MAX_VERSION_COUNT_OVERFLOW

	.set SN_STATE, 0
	.set SN_NL, 2
	.set SN_MARK, 3
	.set SN_DYN, 4
	.set SN_L0, 8
	.set SN_L0T, 12
	.set SN_POS, 16
	.set SN_EXT, 20
	.set SN_SIZE, 24
	.set XB_NEXT, 56
	.set XB_SIZE, 64
	.set H_NODE, 0
	.set H_DEAD, 4
	.set SL_VER, 0
	.set SL_OFF, 4
	.set SL_LEN, 8
	.set IT_NODE, 0
	.set IT_COUNT, 4
	.set IT_CELL, 8

	.set N_SYM, 0
	.set N_PROD, 2
	.set N_EXTRA, 3
	.set N_START, 4
	.set N_END, 8
	.set N_CC, 12
	.set N_CI, 16
	.set N_DYN, 20
	.set N_SIZE, 24

	.text

# ---------------------------------------------------------------------------
# grow helpers: preserve every GPR (except rax where documented), realign stack for libc
# ---------------------------------------------------------------------------
.macro SAVE_VOLATILE
	push rbp
	mov rbp, rsp
	push rax
	push rcx
	push rdx
	push rsi
	push rdi
	push r8
	push r9
	push r10
	push r11
	and rsp, -16
.endm
.macro RESTORE_VOLATILE
	lea rsp, [rbp-72]
	pop r11
	pop r10
	pop r9
	pop r8
	pop rdi
	pop rsi
	pop rdx
	pop rcx
	pop rax
	pop rbp
.endm

# Growable buffers share one layout: qword pointer at +0, dword capacity (entries) at +12.
#
# p_grow(rdi = buffer, esi = entries needed, ecx = entry size in bytes): grow to at least esi
# entries (doubling, at least 256). The size increase is charged to C_MEMUSED against
# C_MEMLIMIT before realloc, and pointer, capacity and usage are stored only after realloc
# succeeds, so an aborted parse leaves a consistent context. Preserves every GPR.
p_grow:
	SAVE_VOLATILE
	mov r8, rdi
	mov r9d, dword ptr [r8+12]
	mov edx, 256
	cmp edx, r9d
	cmovb edx, r9d
1:	cmp edx, esi
	jae 2f
	add edx, edx
	jc p_limit
	jmp 1b
2:	mov eax, edx
	sub eax, r9d
	imul rax, rcx
	add rax, qword ptr [r15+C_MEMUSED]
	cmp rax, qword ptr [r15+C_MEMLIMIT]
	ja p_limit
	mov r10d, r9d
	imul r10, rcx                       # old bytes
	mov r11d, edx
	imul r11, rcx                       # new bytes
	sub rsp, 48                         # [0] capacity, [8] usage, [16] buffer, [24] old bytes, [40] new pointer
	mov qword ptr [rsp], rdx
	mov qword ptr [rsp+8], rax
	mov qword ptr [rsp+16], r8
	mov qword ptr [rsp+24], r10
	mov qword ptr [rsp+32], r11
	mov rdi, qword ptr [r8]
	cmp r11, MAP_MIN                    # small: malloc's heap
	jae 3f
	mov rsi, r11
	call realloc@PLT
	test rax, rax
	jz p_oom
	jmp 5f
3:	cmp r10, MAP_MIN                    # already mapped: grow the mapping
	jb 4f
	mov rsi, r10
	mov rdx, r11
	mov ecx, 1                          # MREMAP_MAYMOVE
	xor eax, eax                        # variadic
	call mremap@PLT
	cmp rax, -1
	je p_oom
	jmp 5f
4:	xor edi, edi                        # crossing MAP_MIN: map, copy, free the heap block
	mov rsi, r11
	mov edx, 3                          # PROT_READ | PROT_WRITE
	mov ecx, 0x22                       # MAP_PRIVATE | MAP_ANONYMOUS
	mov r8, -1
	xor r9d, r9d
	call mmap@PLT
	cmp rax, -1
	je p_oom
	mov qword ptr [rsp+40], rax
	mov rdi, rax                        # huge pages: fewer faults when a big parse touches
	mov rsi, qword ptr [rsp+32]         # fresh memory; the flag follows the mapping through
	mov edx, 14                         # mremap (MADV_HUGEPAGE; failure is harmless)
	call madvise@PLT
	mov rax, qword ptr [rsp+40]
	mov rdx, qword ptr [rsp+24]
	test rdx, rdx
	jz 6f
	mov rdi, rax
	mov r8, qword ptr [rsp+16]
	mov rsi, qword ptr [r8]
	call memcpy@PLT
6:	mov r8, qword ptr [rsp+16]
	mov rdi, qword ptr [r8]
	call free@PLT
	mov rax, qword ptr [rsp+40]
5:	mov r8, qword ptr [rsp+16]
	mov rdx, qword ptr [rsp]
	mov rcx, qword ptr [rsp+8]
	mov qword ptr [r8], rax
	mov dword ptr [r8+12], edx
	mov qword ptr [r15+C_MEMUSED], rcx
	RESTORE_VOLATILE
	ret

# p_grow_nodes: make nn < navail, growing the arena if needed; the node budget C_NODELIM is
# enforced here, so a capacity kept from an earlier parse cannot lift it. Preserves every GPR.
p_grow_nodes:
	push rdi
	push rsi
	push rcx
	mov esi, dword ptr [r15+C_NN]
	cmp esi, dword ptr [r15+C_NODELIM]
	jae p_limit
	cmp esi, dword ptr [r15+C_NCAP]
	jb 1f
	inc esi
	lea rdi, [r15+C_NODES]
	mov ecx, N_SIZE
	call p_grow
1:	call p_set_navail
	pop rcx
	pop rsi
	pop rdi
	ret

# p_set_navail: C_NAVAIL = min(C_NCAP, C_NODELIM). Preserves every GPR but rcx.
p_set_navail:
	mov ecx, dword ptr [r15+C_NCAP]
	cmp ecx, dword ptr [r15+C_NODELIM]
	cmova ecx, dword ptr [r15+C_NODELIM]
	mov dword ptr [r15+C_NAVAIL], ecx
	ret

# p_grow_kids(edi = count): make nk + edi <= kcap. Preserves every GPR.
p_grow_kids:
	push rdi
	push rsi
	push rcx
	mov esi, dword ptr [r15+C_NK]
	add esi, edi
	jc p_limit
	lea rdi, [r15+C_KIDS]
	mov ecx, 4
	call p_grow
	pop rcx
	pop rsi
	pop rdi
	ret

# p_grow_estk(esi = frames): 16-byte frames used by emit, subtree compare, stack collection and link merging. Preserves every GPR.
p_grow_estk:
	push rdi
	push rcx
	lea rdi, [r15+C_ESTK]
	mov ecx, 16
	call p_grow
	pop rcx
	pop rdi
	ret

# Budget aborts unwind straight to the end of tsasm_parse_go.
p_limit:
	mov eax, ERR_LIMIT
	jmp 1f
p_oom:
	mov eax, ERR_NOMEM
1:	mov rsp, qword ptr [r15+C_SAVEDRSP]
	movsxd rax, eax
	jmp .Lmain_ret


# RELEASE off, size: free buffer off (entries of size bytes) and zero it. Stack aligned.
.macro RELEASE off, size
	mov rdi, qword ptr [r15+\off]
	mov esi, dword ptr [r15+\off+12]
	imul rsi, rsi, \size
	call p_free_buf
	mov qword ptr [r15+\off], 0
	mov dword ptr [r15+\off+12], 0
.endm

# p_free_buf(rdi = pointer, rsi = capacity in bytes): munmap or free, as p_grow allocated it.
p_free_buf:
	cmp rsi, MAP_MIN
	jae munmap@PLT
	jmp free@PLT

# p_release_work: free every buffer but the output array; usage drops to the output's (r15 = ctx).
p_release_work:
	push rbx
	RELEASE C_NODES, N_SIZE
	RELEASE C_KIDS, 4
	RELEASE C_ESTK, 16
	RELEASE C_SN, SN_SIZE
	RELEASE C_XB, XB_SIZE
	RELEASE C_HEADS, 8
	RELEASE C_SLICES, 16
	RELEASE C_CELLS, 8
	RELEASE C_SLK, 4
	mov eax, dword ptr [r15+C_OUTCAP]
	shl rax, 4
	mov qword ptr [r15+C_MEMUSED], rax
	pop rbx
	ret

# p_release: free every buffer the context owns and zero their capacities (r15 = ctx).
p_release:
	push rbx
	call p_release_work
	RELEASE C_OUT, 16
	mov qword ptr [r15+C_MEMUSED], 0
	pop rbx
	ret

# TREE_OFF reg64: tree index -> byte offset in the arena (index * N_SIZE)
.macro TREE_OFF reg
	lea \reg, [\reg + \reg*2]
	shl \reg, 3
.endm

# ALLOC_NODE reg32: reg = new node index (nn++), may grow (preserves regs)
.macro ALLOC_NODE reg
	mov \reg, dword ptr [r15+C_NN]
	cmp \reg, dword ptr [r15+C_NAVAIL]
	jb 91f
	call p_grow_nodes
91:	inc dword ptr [r15+C_NN]
.endm

# ---------------------------------------------------------------------------
# p_lex(edi = parse state, esi = byte position) -> eax = 1 token lexed into cache, 0 = no token
# ---------------------------------------------------------------------------
	.p2align 4
p_lex:
	push rbx
	push r12
	push r13
	mov ebx, edi
	mov dword ptr [r15+C_TPOS], esi
	mov dword ptr [r15+C_TPSTATE], edi
	mov rsi, qword ptr [r15+C_SRC]
	mov r12, rsi                        # r12 = src base
	mov eax, dword ptr [r15+C_TPOS]
	add rsi, rax
	mov r9, qword ptr [r15+C_END]
	mov rax, qword ptr [r15+C_LANG+L_LEX_STATE]
	movzx ecx, word ptr [rax + rbx*2]
	call qword ptr [r15+C_LANG+L_LEX_MAIN]
	cmp ecx, -1
	je .Llex_fail
	sub r10, r12
	sub r11, r12
	cmp r11, r10                        # a token accepted before skipped whitespace starts where
	jae 1f                              # it ends, as in ts_lexer_finish
	mov r10, r11
1:	mov dword ptr [r15+C_TSTART], r10d
	mov dword ptr [r15+C_TEND], r11d
	mov dword ptr [r15+C_TKW], 0
	cmp ecx, dword ptr [r15+C_LANG+L_WORD]
	jne .Llex_store
	cmp qword ptr [r15+C_LANG+L_LEX_KEYWORD], 0
	je .Llex_store
	# keyword extraction
	mov r13d, r11d                      # identifier end offset
	lea rsi, [r12 + r10]
	call qword ptr [r15+C_LANG+L_LEX_KEYWORD]
	cmp ecx, -1
	je .Llex_word
	mov dword ptr [r15+C_TKW], 1
	sub r11, r12
	cmp r11d, r13d
	jne .Llex_word
	# has_actions(state, kw) || is_reserved(state, kw)
	mov eax, ebx
	imul eax, dword ptr [r15+C_LANG+L_NSYM]
	add eax, ecx
	mov rdx, qword ptr [r15+C_LANG+L_PARSE_TABLE]
	movzx eax, word ptr [rdx + rax*2]
	test eax, eax
	jnz .Llex_store
	mov rdx, qword ptr [r15+C_LANG+L_RESERVED_SET]
	movzx eax, byte ptr [rdx + rbx]
	imul eax, dword ptr [r15+C_LANG+L_RWORDS]
	mov edx, ecx
	shr edx, 6
	add eax, edx
	mov rdx, qword ptr [r15+C_LANG+L_RESERVED_BITS]
	mov rax, qword ptr [rdx + rax*8]
	bt rax, rcx
	jc .Llex_store
.Llex_word:
	mov ecx, dword ptr [r15+C_LANG+L_WORD]
.Llex_store:
	mov dword ptr [r15+C_TSYM], ecx
	mov dword ptr [r15+C_TOKVALID], 1
	mov eax, 1
	pop r13
	pop r12
	pop rbx
	ret
.Llex_fail:
	mov dword ptr [r15+C_TOKVALID], 0
	xor eax, eax
	pop r13
	pop r12
	pop rbx
	ret

# ---------------------------------------------------------------------------
# p_can_reuse(edi = state) -> eax (cached token reusable in this state)
# ---------------------------------------------------------------------------
	.p2align 4
p_can_reuse:
	mov ecx, dword ptr [r15+C_TSYM]
	mov eax, edi
	imul eax, dword ptr [r15+C_LANG+L_NSYM]
	add eax, ecx
	mov rdx, qword ptr [r15+C_LANG+L_PARSE_TABLE]
	movzx eax, word ptr [rdx + rax*2]
	mov rdx, qword ptr [r15+C_LANG+L_ACTIONS]
	mov r8, qword ptr [rdx + rax*8]     # header
	test r8b, r8b
	jz .Lcr_size
	mov esi, dword ptr [r15+C_TPSTATE]
	mov rdx, qword ptr [r15+C_LANG+L_LEX_STATE]
	movzx eax, word ptr [rdx + rsi*2]
	movzx r9d, word ptr [rdx + rdi*2]
	cmp eax, r9d
	jne .Lcr_size
	mov rdx, qword ptr [r15+C_LANG+L_RESERVED_SET]
	movzx eax, byte ptr [rdx + rsi]
	movzx r9d, byte ptr [rdx + rdi]
	cmp eax, r9d
	jne .Lcr_size
	cmp ecx, dword ptr [r15+C_LANG+L_WORD]
	jne .Lcr_yes
	cmp dword ptr [r15+C_TKW], 0
	jne .Lcr_size
	cmp esi, edi
	je .Lcr_yes
.Lcr_size:
	mov eax, dword ptr [r15+C_TEND]
	cmp eax, dword ptr [r15+C_TSTART]
	jne .Lcr_flag
	test ecx, ecx
	jz .Lcr_flag
	xor eax, eax
	ret
.Lcr_flag:
	mov rax, r8
	shr eax, 8
	and eax, 1
	ret
.Lcr_yes:
	mov eax, 1
	ret

# ---------------------------------------------------------------------------
# Graph-structured stack: C tree-sitter's stack.c, the parts error-free parsing needs.
# Stack nodes are recycled: a single-version reduce frees the nodes it pops (p_reduce_fast), and
# p_gc collects the rest when the arena is full. Trees live in the append-only tree arena.
# ---------------------------------------------------------------------------

# p_snode_slow -> eax = a free stack node. Preserves every GPR but rax.
p_snode_slow:
	mov eax, dword ptr [r15+C_SFREE]
	test eax, eax
	jnz 2f
	mov eax, dword ptr [r15+C_SNN]
	cmp eax, dword ptr [r15+C_SNCAP]
	jae 1f
	inc dword ptr [r15+C_SNN]
	ret
1:	call p_gc
	jmp p_snode_slow
2:	push rcx
	lea rcx, [rax+rax*2]
	shl rcx, 3
	add rcx, qword ptr [r15+C_SN]
	mov ecx, dword ptr [rcx+SN_L0]
	mov dword ptr [r15+C_SFREE], ecx
	pop rcx
	ret

# p_gc: mark the stack nodes reachable from the heads, sweep the rest into the free list (with
# their extension blocks), and double the arena if less than half of it came free. Only called
# from allocation, when every live node is reachable from a head. Preserves every GPR.
p_gc:
	push rax
	push rbx
	push rcx
	push rdx
	push rsi
	push rdi
	push r8
	push r9
	push r10
	push r11
	mov r8, qword ptr [r15+C_SN]
	mov byte ptr [r8+SN_MARK], 1          # the base node
	xor esi, esi                          # mark stack depth (u32 entries in the frame buffer)
	xor edx, edx
.Lgc_root:
	cmp edx, dword ptr [r15+C_NH]
	jae .Lgc_sweep
	mov rax, qword ptr [r15+C_HEADS]
	mov eax, dword ptr [rax + rdx*8 + H_NODE]
	inc edx
	call .Lgc_mark
.Lgc_drain:
	test esi, esi
	jz .Lgc_root
	dec esi
	mov rbx, qword ptr [r15+C_ESTK]
	mov eax, dword ptr [rbx + rsi*4]
	lea rcx, [rax+rax*2]
	lea rcx, [r8 + rcx*8]
	movzx edi, byte ptr [rcx+SN_NL]
	test edi, edi
	jz .Lgc_drain
	mov eax, dword ptr [rcx+SN_L0]
	call .Lgc_mark
	dec edi
	jz .Lgc_drain
	mov r9d, dword ptr [rcx+SN_EXT]
	shl r9, 6
	add r9, qword ptr [r15+C_XB]
1:	mov eax, dword ptr [r9]
	call .Lgc_mark
	add r9, 8
	dec edi
	jnz 1b
	jmp .Lgc_drain
.Lgc_sweep:                             # a free node's link count is 0 or 1 (no extension block)
	xor r10d, r10d                        # free list
	xor r11d, r11d                        # nodes marked
	mov ecx, dword ptr [r15+C_SNN]
	mov rdx, qword ptr [r15+C_XB]
	lea rax, [rcx+rcx*2]
	lea rax, [r8 + rax*8]
3:	dec ecx
	jz 6f
	sub rax, SN_SIZE
	movzx edi, word ptr [rax+SN_NL]       # link count | mark << 8
	cmp edi, 1
	ja 4f
5:	mov dword ptr [rax+SN_L0], r10d
	mov r10d, ecx
	jmp 3b
4:	cmp edi, 0x100
	jb 8f
	mov byte ptr [rax+SN_MARK], 0
	inc r11d
	jmp 3b
8:	mov edi, dword ptr [rax+SN_EXT]
	mov ebx, edi
	shl rbx, 6
	mov esi, dword ptr [r15+C_XFREE]
	mov dword ptr [rdx + rbx + XB_NEXT], esi
	mov dword ptr [r15+C_XFREE], edi
	mov byte ptr [rax+SN_NL], 0
	jmp 5b
6:	mov byte ptr [r8+SN_MARK], 0
	mov dword ptr [r15+C_SFREE], r10d
	mov eax, dword ptr [r15+C_SNN]        # grow unless at least half came free
	mov ecx, eax
	shr ecx, 1
	sub eax, ecx
	inc r11d                              # live nodes, with the base
	cmp r11d, eax
	jbe 7f
	lea rdi, [r15+C_SN]
	mov esi, dword ptr [r15+C_SNCAP]
	inc esi
	mov ecx, SN_SIZE
	call p_grow
7:	pop r11
	pop r10
	pop r9
	pop r8
	pop rdi
	pop rsi
	pop rdx
	pop rcx
	pop rbx
	pop rax
	ret
