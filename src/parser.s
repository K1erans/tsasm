# p_link_addr(edi = stack node, esi = link index) -> rax = address of the link. Preserves the rest.
p_link_addr:
	mov eax, edi
	lea rax, [rax+rax*2]
	shl rax, 3
	add rax, qword ptr [r15+C_SN]
	test esi, esi
	jnz 1f
	add rax, SN_L0
	ret
1:	push rcx
	mov ecx, dword ptr [rax+SN_EXT]
	shl rcx, 6
	add rcx, qword ptr [r15+C_XB]
	mov eax, esi
	lea rax, [rcx + rax*8 - 8]
	pop rcx
	ret

# p_push(edi = version, esi = tree, edx = state): ts_stack_push. Clobbers caller-saved registers.
	.p2align 4
p_push:
	mov edi, edi
	mov eax, dword ptr [r15+C_SFREE]
	test eax, eax
	jz 1f
	lea r8, [rax+rax*2]
	shl r8, 3
	add r8, qword ptr [r15+C_SN]
	mov ecx, dword ptr [r8+SN_L0]
	mov dword ptr [r15+C_SFREE], ecx
	jmp 2f
1:	call p_snode_slow
	lea r8, [rax+rax*2]
	shl r8, 3
	add r8, qword ptr [r15+C_SN]
2:	mov r9, qword ptr [r15+C_HEADS]
	mov ecx, dword ptr [r9 + rdi*8 + H_NODE]  # previous node
	mov dword ptr [r9 + rdi*8 + H_NODE], eax
	or edx, 0x10000                       # state, one link, unmarked
	mov dword ptr [r8+SN_STATE], edx
	mov dword ptr [r8+SN_L0], ecx
	mov dword ptr [r8+SN_L0T], esi
	mov dword ptr [r8+SN_EXT], 0
	mov r10, qword ptr [r15+C_NODES]
	mov r11d, esi
	TREE_OFF r11
	mov edx, dword ptr [r10 + r11 + N_END]
	mov dword ptr [r8+SN_POS], edx
	mov edx, dword ptr [r10 + r11 + N_DYN]
	lea r11, [rcx+rcx*2]
	shl r11, 3
	add r11, qword ptr [r15+C_SN]
	add edx, dword ptr [r11+SN_DYN]
	mov dword ptr [r8+SN_DYN], edx
	ret

# SHIFT_LEAF (edi = version, esi = state, edx = symbol, ecx = extra flag): push a leaf for the
# cached token (ts_stack_push; a leaf's precedence is 0, so the node's is its predecessor's).
# Clobbers caller-saved registers.
.macro SHIFT_LEAF
	test edx, edx
	jnz .Lsl_a\@
	mov ecx, 1                          # eof is always extra
.Lsl_a\@:
	ALLOC_NODE eax
	mov r8, qword ptr [r15+C_NODES]
	mov r9d, eax
	TREE_OFF r9
	add r9, r8
	shl ecx, 24
	or ecx, edx                         # symbol | extra<<24 (prod = 0)
	mov dword ptr [r9+N_SYM], ecx
	mov r10, qword ptr [r15+C_TSTART]   # start, end
	mov qword ptr [r9+N_START], r10
	mov qword ptr [r9+N_CC], 0
	mov dword ptr [r9+N_DYN], 0
	mov edi, edi
	mov r11d, eax                       # the leaf
	mov eax, dword ptr [r15+C_SFREE]
	test eax, eax
	jz .Lsl_b\@
	mov r8, qword ptr [r15+C_SN]
	lea rcx, [rax+rax*2]
	mov ecx, dword ptr [r8 + rcx*8 + SN_L0]
	mov dword ptr [r15+C_SFREE], ecx
	jmp .Lsl_c\@
.Lsl_b\@:
	call p_snode_slow
	mov r8, qword ptr [r15+C_SN]
.Lsl_c\@:
	mov r9, qword ptr [r15+C_HEADS]
	mov ecx, dword ptr [r9 + rdi*8 + H_NODE]  # previous node
	mov dword ptr [r9 + rdi*8 + H_NODE], eax
	lea rax, [rax+rax*2]
	lea rax, [r8 + rax*8]
	or esi, 0x10000                       # state, one link, unmarked
	mov dword ptr [rax+SN_STATE], esi
	mov dword ptr [rax+SN_L0], ecx
	mov dword ptr [rax+SN_L0T], r11d
	mov dword ptr [rax+SN_EXT], 0
	shr r10, 32
	mov dword ptr [rax+SN_POS], r10d
	lea rcx, [rcx+rcx*2]
	mov ecx, dword ptr [r8 + rcx*8 + SN_DYN]
	mov dword ptr [rax+SN_DYN], ecx
.endm

# p_shift: SHIFT_LEAF as a function
	.p2align 4
p_shift:
	SHIFT_LEAF
	ret

# p_reduce_fast(edi = version, rsi = reduce action, edx = 1 if this is the state's only action)
# -> eax = the version holding the result, -1 if it merged into an earlier version, -2 if nothing
# was done (p_reduce_gss takes over). It handles the path when every node on it has one link, so
# it is the only one. As in C, the result goes on a new version that may merge into an earlier
# one. With one version and one action, C then renumbers the new version to 0, so the parent is
# built straight on version 0 and the popped nodes (no other version reaches them) go back to the
# free list.
	.set RF_VER, 0
	.set RF_INPLACE, 4
	.set RF_PARENT, 8
	.set RF_KIDS, 12
	.set RF_RES, 16
	.set RF_SINGLE, 20
	.set RF_ACTION, 24
	.set RF_ENDS, 32                    # 8 slices' base nodes
	.set RF_I, 64
	.set RF_H, 68
	.set RF_L, 72
	.set RF_C, 76
	.set RF_F, 80
	.set RF_D, 84
	.p2align 4
p_reduce_fast:
	push rbx
	push rbp
	push r12
	push r13
	push r14
	sub rsp, 96
	mov dword ptr [rsp+RF_VER], edi
	mov dword ptr [rsp+RF_RES], edi
	mov qword ptr [rsp+RF_ACTION], rsi
	mov dword ptr [rsp+RF_SINGLE], edx
	mov eax, dword ptr [r15+C_NH]
	cmp eax, 1
	jne 1f
	mov dword ptr [rsp+RF_INPLACE], edx
	jmp .Lrf_quick
1:	mov dword ptr [rsp+RF_INPLACE], 0
	cmp eax, MAXSLICEVER                # p_reduce_gss drops the new version
	jb .Lrf_quick
	jmp .Lrf_bail
.Lrf_general:
	mov rsi, qword ptr [rsp+RF_ACTION]
	mov edi, dword ptr [rsp+RF_VER]
	mov eax, esi
	shr eax, 8
	movzx ebp, al                       # non-extra entries to pop
	mov r8, qword ptr [r15+C_SN]
	mov r9, qword ptr [r15+C_NODES]
	mov rax, qword ptr [r15+C_HEADS]
	mov ebx, dword ptr [rax + rdi*8 + H_NODE]
	mov ecx, ebx
	xor edx, edx                        # non-extra entries seen
	xor r13d, r13d                      # entries seen
	xor r14d, r14d                      # trailing extras (above the topmost non-extra entry)
.Lrf_walk:
	cmp edx, ebp
	je .Lrf_found
	lea rax, [rcx+rcx*2]
	lea r10, [r8 + rax*8]
	cmp byte ptr [r10+SN_NL], 1
	jne .Lrf_bail
	mov eax, dword ptr [r10+SN_L0T]
	mov ecx, dword ptr [r10+SN_L0]
	inc r13d
	TREE_OFF rax
	cmp byte ptr [r9 + rax + N_EXTRA], 0
	jne 1f
	inc edx
	jmp .Lrf_walk
1:	test edx, edx
	jnz .Lrf_walk
	inc r14d
	jmp .Lrf_walk
.Lrf_bail:
	mov eax, -2
	jmp .Lrf_ret
.Lrf_found:
	mov ebp, ecx                        # base node
	mov edi, r13d
	sub edi, r14d                       # children
	mov dword ptr [rsp+RF_KIDS], edi
	mov eax, dword ptr [r15+C_NK]
	add eax, edi
	cmp eax, dword ptr [r15+C_KCAP]
	jbe 1f
	call p_grow_kids
1:	cmp r14d, dword ptr [r15+C_SLKCAP]
	jbe 2f
	push rdi
	push rdi
	lea rdi, [r15+C_SLK]
	mov esi, r14d
	mov ecx, 4
	call p_grow
	pop rdi
	pop rdi
2:	ALLOC_NODE eax                      # parent
	mov dword ptr [rsp+RF_PARENT], eax
	mov r8, qword ptr [r15+C_SN]
	mov r9, qword ptr [r15+C_NODES]
	mov r10, qword ptr [r15+C_KIDS]
	mov r11, qword ptr [r15+C_SLK]
	mov esi, dword ptr [r15+C_NK]
	add esi, edi                        # children are written downward from here
	xor edx, edx                        # entries taken
	xor edi, edi                        # children's dynamic precedence
	mov eax, dword ptr [r15+C_SFREE]
	mov ecx, ebx
.Lrf_take:
	cmp edx, r13d
	jae .Lrf_built
	lea rbx, [rcx+rcx*2]
	lea rbx, [r8 + rbx*8]
	mov r12d, ecx
	mov ecx, dword ptr [rbx+SN_L0]
	cmp dword ptr [rsp+RF_INPLACE], 0
	je 1f
	mov dword ptr [rbx+SN_L0], eax      # back to the free list
	mov eax, r12d
1:	mov ebx, dword ptr [rbx+SN_L0T]
	cmp edx, r14d
	jae 3f
	mov dword ptr [r11 + rdx*4], ebx    # a trailing extra, topmost first
	inc edx
	jmp .Lrf_take
3:	dec esi
	mov dword ptr [r10 + rsi*4], ebx
	TREE_OFF rbx
	add edi, dword ptr [r9 + rbx + N_DYN]
	inc edx
	jmp .Lrf_take
.Lrf_built:
	mov r12, qword ptr [rsp+RF_ACTION]
	cmp dword ptr [rsp+RF_INPLACE], 0
	je 1f
	mov dword ptr [r15+C_SFREE], eax
	mov rax, qword ptr [r15+C_HEADS]
	mov ecx, dword ptr [rsp+RF_VER]
	mov dword ptr [rax + rcx*8 + H_NODE], ebp
	jmp 2f
1:	mov ebx, edi
	mov edi, ebp
	call p_add_version
	mov dword ptr [rsp+RF_RES], eax
	mov edi, ebx
2:	mov ecx, dword ptr [rsp+RF_KIDS]
	mov eax, dword ptr [rsp+RF_PARENT]
	mov rdx, rax
	TREE_OFF rdx
	add rdx, r9
	mov r11, r12
	shr r11, 16
	movzx ebx, r11w                     # symbol
	shr r11, 16
	movzx r11d, r11b
	shl r11d, 16
	or r11d, ebx
	mov dword ptr [rdx+N_SYM], r11d
	mov dword ptr [rdx+N_CC], ecx
	mov esi, dword ptr [r15+C_NK]
	mov dword ptr [rdx+N_CI], esi
	test ecx, ecx
	jz 4f
	mov r11, r12
	sar r11, 48
	add edi, r11d                       # the action's dynamic precedence
	mov dword ptr [rdx+N_DYN], edi
	mov r11d, dword ptr [r10 + rsi*4]
	TREE_OFF r11
	mov r11d, dword ptr [r9 + r11 + N_START]
	mov dword ptr [rdx+N_START], r11d
	add esi, ecx
	mov dword ptr [r15+C_NK], esi
	mov r11d, dword ptr [r10 + rsi*4 - 4]
	TREE_OFF r11
	mov r11d, dword ptr [r9 + r11 + N_END]
	mov dword ptr [rdx+N_END], r11d
	jmp 5f
4:	mov dword ptr [rdx+N_DYN], 0        # C reads a childless node's precedence as 0
	lea r11, [rbp+rbp*2]
	mov r11d, dword ptr [r8 + r11*8 + SN_POS]
	mov dword ptr [rdx+N_START], r11d
	mov dword ptr [rdx+N_END], r11d
5:	lea r11, [rbp+rbp*2]
	movzx ecx, word ptr [r8 + r11*8 + SN_STATE]
	imul ecx, dword ptr [r15+C_LANG+L_NSYM]
	add ecx, ebx
	mov rdx, qword ptr [r15+C_LANG+L_PARSE_TABLE]
	movzx ebp, word ptr [rdx + rcx*2]   # next state
	mov edi, dword ptr [rsp+RF_RES]
	mov esi, eax
	mov edx, ebp
	call p_push
6:	test r14d, r14d                     # trailing extras go back on top, bottom first
	jz 7f
	dec r14d
	mov rax, qword ptr [r15+C_SLK]
	mov edi, dword ptr [rsp+RF_RES]
	mov esi, dword ptr [rax + r14*4]
	mov edx, ebp
	call p_push
	jmp 6b
7:	cmp dword ptr [rsp+RF_INPLACE], 0   # merge into the first earlier version that accepts it
	jne 9f
	xor ebx, ebx
8:	cmp ebx, dword ptr [rsp+RF_RES]
	jae 9f
	cmp ebx, dword ptr [rsp+RF_VER]
	je 1f
	mov edi, ebx
	mov esi, dword ptr [rsp+RF_RES]
	call p_merge
	test eax, eax
	jz 1f
	mov dword ptr [rsp+RF_RES], -1
	jmp 9f
1:	inc ebx
	jmp 8b
9:	mov eax, dword ptr [rsp+RF_RES]
	jmp .Lrf_ret

# No extras among the popped entries and at least one child: one pass writes the children and the
# parent gets a new node, which merges into the first earlier head it matches or becomes a new
# version. (ADVANCE does the one-version case in place.)
.Lrf_quick:
	mov eax, esi
	shr eax, 8
	movzx ebp, al                       # children
	test ebp, ebp
	jz .Lrf_general
	mov eax, dword ptr [r15+C_NK]
	lea esi, [rax + rbp]
	cmp esi, dword ptr [r15+C_KCAP]
	ja .Lrf_general
	mov r8, qword ptr [r15+C_SN]
	mov r9, qword ptr [r15+C_NODES]
	mov r10, qword ptr [r15+C_KIDS]
	mov rax, qword ptr [r15+C_HEADS]
	mov ebx, dword ptr [rsp+RF_VER]
	mov ebx, dword ptr [rax + rbx*8 + H_NODE]
	lea rax, [rbx+rbx*2]
	cmp byte ptr [r8 + rax*8 + SN_NL], 1
	ja .Lrf_fork
	mov ecx, ebx
	xor edi, edi                        # children's dynamic precedence
	mov edx, ebp
1:	lea rax, [rcx+rcx*2]
	lea r11, [r8 + rax*8]
	cmp byte ptr [r11+SN_NL], 1
	jne .Lrf_forkd
	mov eax, dword ptr [r11+SN_L0T]
	mov r14d, ecx                       # the lowest popped node
	mov ecx, dword ptr [r11+SN_L0]
	mov r12, rax
	TREE_OFF r12
	cmp byte ptr [r9 + r12 + N_EXTRA], 0
	jne .Lrf_general
	dec esi
	mov dword ptr [r10 + rsi*4], eax
	add edi, dword ptr [r9 + r12 + N_DYN]
	dec edx
	jnz 1b
	ALLOC_NODE eax                      # parent; ecx = base node
	mov r9, qword ptr [r15+C_NODES]
	mov rdx, rax
	TREE_OFF rdx
	add rdx, r9
	mov r12, qword ptr [rsp+RF_ACTION]
	mov r11, r12
	shr r11, 16
	movzx r13d, r11w                    # symbol
	shr r11, 16
	movzx r11d, r11b
	shl r11d, 16
	or r11d, r13d
	mov dword ptr [rdx+N_SYM], r11d
	mov dword ptr [rdx+N_CC], ebp
	mov dword ptr [rdx+N_CI], esi
	sar r12, 48
	add edi, r12d                       # the action's dynamic precedence
	mov dword ptr [rdx+N_DYN], edi
	mov r11d, dword ptr [r10 + rsi*4]
	TREE_OFF r11
	mov r11d, dword ptr [r9 + r11 + N_START]
	mov dword ptr [rdx+N_START], r11d
	add esi, ebp
	mov dword ptr [r15+C_NK], esi
	mov r11d, dword ptr [r10 + rsi*4 - 4]
	TREE_OFF r11
	mov r11d, dword ptr [r9 + r11 + N_END]
	mov dword ptr [rdx+N_END], r11d
	lea r11, [rcx+rcx*2]
	lea r11, [r8 + r11*8]               # base node
	movzx edx, word ptr [r11+SN_STATE]
	imul edx, dword ptr [r15+C_LANG+L_NSYM]
	add edx, r13d
	mov r12, qword ptr [r15+C_LANG+L_PARSE_TABLE]
	movzx edx, word ptr [r12 + rdx*2]   # next state
	add edi, dword ptr [r11+SN_DYN]
	lea r12, [rbx+rbx*2]
	lea r12, [r8 + r12*8]
.Lrf_qnew:
	mov r13d, dword ptr [r12+SN_POS]
	mov r12d, eax                       # parent
	mov ebx, dword ptr [rsp+RF_VER]
	call .Lrf_place
	test edx, edx
	jz 1f
	mov eax, -1
	jmp .Lrf_ret
1:	cmp dword ptr [rsp+RF_SINGLE], 0    # the only action: C would renumber the new version here
	je 2f
	mov rcx, qword ptr [r15+C_HEADS]
	mov dword ptr [rcx + rbx*8 + H_NODE], eax
	mov eax, ebx
	jmp .Lrf_ret
2:	mov edi, eax
	call p_add_version
	jmp .Lrf_ret

# The popped path has one link per node and no extras except at one fork node, the head or one
# of the first d nodes' predecessors, whose links lead to distinct base nodes: each link is a
# slice with its own version (ts_stack_pop_count then ts_parser__reduce). A slice's version is
# created when it is reduced, which gives it the index C's would have by then.
.Lrf_forkd:                             # ecx = the fork node, after ebp - edx entries
	mov eax, ebp
	sub eax, edx
	mov dword ptr [rsp+RF_D], eax
	mov dword ptr [rsp+RF_F], ecx
	jmp 7f
.Lrf_fork:                              # ebx = head node, ebp = children, r8 = nodes, r9 = trees
	mov dword ptr [rsp+RF_D], 0
	mov dword ptr [rsp+RF_F], ebx
7:	mov dword ptr [rsp+RF_H], ebx
	mov dword ptr [rsp+RF_C], ebp
	mov eax, dword ptr [rsp+RF_F]
	lea rax, [rax+rax*2]
	movzx eax, byte ptr [r8 + rax*8 + SN_NL]
	mov dword ptr [rsp+RF_L], eax
	imul eax, ebp
	add eax, dword ptr [r15+C_NK]
	cmp eax, dword ptr [r15+C_KCAP]
	ja .Lrf_general
	xor esi, esi                        # link
1:	cmp esi, dword ptr [rsp+RF_L]
	jae 4f
	mov edi, dword ptr [rsp+RF_F]
	call p_link_addr
	mov ecx, dword ptr [rax]
	mov eax, dword ptr [rax+4]
	TREE_OFF rax
	cmp byte ptr [r9 + rax + N_EXTRA], 0
	jne .Lrf_general
	mov edx, ebp
	sub edx, dword ptr [rsp+RF_D]
2:	dec edx
	jz 3f
	lea rax, [rcx+rcx*2]
	lea r11, [r8 + rax*8]
	cmp byte ptr [r11+SN_NL], 1
	jne .Lrf_general
	mov eax, dword ptr [r11+SN_L0T]
	mov ecx, dword ptr [r11+SN_L0]
	TREE_OFF rax
	cmp byte ptr [r9 + rax + N_EXTRA], 0
	jne .Lrf_general
	jmp 2b
3:	xor edx, edx                        # slices ending at one node are grouped: p_reduce_gss
5:	cmp edx, esi
	jae 6f
	cmp ecx, dword ptr [rsp + RF_ENDS + rdx*4]
	je .Lrf_general
	inc edx
	jmp 5b
6:	mov dword ptr [rsp + RF_ENDS + rsi*4], ecx
	inc esi
	jmp 1b
4:	mov eax, dword ptr [r15+C_NH]
	mov dword ptr [rsp+RF_RES], eax     # the first new version, if any
	mov dword ptr [rsp+RF_I], 0
.Lrf_fslice:
	mov esi, dword ptr [rsp+RF_I]
	cmp esi, dword ptr [rsp+RF_L]
	jae .Lrf_fdone
	cmp dword ptr [r15+C_NH], MAXSLICEVER
	ja .Lrf_fnext                       # C drops this slice's version
	mov ebp, dword ptr [rsp+RF_C]
	ALLOC_NODE eax                      # parent
	mov dword ptr [rsp+RF_PARENT], eax
	mov edi, dword ptr [rsp+RF_F]
	call p_link_addr
	mov r12d, dword ptr [rax]
	mov r13d, dword ptr [rax+4]
	mov r8, qword ptr [r15+C_SN]
	mov r9, qword ptr [r15+C_NODES]
	mov r10, qword ptr [r15+C_KIDS]
	mov esi, dword ptr [r15+C_NK]
	add esi, ebp                        # children are written downward from here
	xor edi, edi                        # children's dynamic precedence
	mov ecx, dword ptr [rsp+RF_H]
	mov edx, dword ptr [rsp+RF_D]
1:	test edx, edx                       # the shared entries above the fork
	jz 4f
	lea rax, [rcx+rcx*2]
	lea r11, [r8 + rax*8]
	mov eax, dword ptr [r11+SN_L0T]
	mov ecx, dword ptr [r11+SN_L0]
	dec esi
	mov dword ptr [r10 + rsi*4], eax
	TREE_OFF rax
	add edi, dword ptr [r9 + rax + N_DYN]
	dec edx
	jmp 1b
4:	mov ecx, r12d                       # this slice's link
	dec esi
	mov dword ptr [r10 + rsi*4], r13d
	TREE_OFF r13
	add edi, dword ptr [r9 + r13 + N_DYN]
	mov edx, ebp
	sub edx, dword ptr [rsp+RF_D]
2:	dec edx
	jz 3f
	lea rax, [rcx+rcx*2]
	lea r11, [r8 + rax*8]
	mov eax, dword ptr [r11+SN_L0T]
	mov ecx, dword ptr [r11+SN_L0]
	dec esi
	mov dword ptr [r10 + rsi*4], eax
	TREE_OFF rax
	add edi, dword ptr [r9 + rax + N_DYN]
	jmp 2b
3:	mov eax, dword ptr [rsp+RF_PARENT]  # ecx = the slice's base node
	mov rdx, rax
	TREE_OFF rdx
	add rdx, r9
	mov r12, qword ptr [rsp+RF_ACTION]
	mov r11, r12
	shr r11, 16
	movzx r13d, r11w                    # symbol
	shr r11, 16
	movzx r11d, r11b
	shl r11d, 16
	or r11d, r13d
	mov dword ptr [rdx+N_SYM], r11d
	mov dword ptr [rdx+N_CC], ebp
	mov dword ptr [rdx+N_CI], esi
	sar r12, 48
	add edi, r12d                       # the action's dynamic precedence
	mov dword ptr [rdx+N_DYN], edi
	mov r11d, dword ptr [r10 + rsi*4]
	TREE_OFF r11
	mov r11d, dword ptr [r9 + r11 + N_START]
	mov dword ptr [rdx+N_START], r11d
	add esi, ebp
	mov dword ptr [r15+C_NK], esi
	mov r11d, dword ptr [r10 + rsi*4 - 4]
	TREE_OFF r11
	mov r11d, dword ptr [r9 + r11 + N_END]
	mov dword ptr [rdx+N_END], r11d
	lea r11, [rcx+rcx*2]
	lea r11, [r8 + r11*8]
	movzx edx, word ptr [r11+SN_STATE]
	imul edx, dword ptr [r15+C_LANG+L_NSYM]
	add edx, r13d
	mov r12, qword ptr [r15+C_LANG+L_PARSE_TABLE]
	movzx edx, word ptr [r12 + rdx*2]   # next state
	add edi, dword ptr [r11+SN_DYN]
	mov r12d, dword ptr [rsp+RF_H]      # every link's tree ends at the head's position
	lea r12, [r12+r12*2]
	mov r13d, dword ptr [r8 + r12*8 + SN_POS]
	mov r12d, eax
	mov ebx, dword ptr [rsp+RF_VER]
	call .Lrf_place
	test edx, edx
	jnz .Lrf_fnext
	mov edi, eax
	call p_add_version
.Lrf_fnext:
	inc dword ptr [rsp+RF_I]
	jmp .Lrf_fslice
.Lrf_fdone:
	mov eax, -1
	mov ecx, dword ptr [rsp+RF_RES]
	cmp dword ptr [r15+C_NH], ecx
	cmova eax, ecx
	jmp .Lrf_ret

# .Lrf_place(ecx = base node, edx = state, edi = precedence, r12d = parent, r13d = position,
# ebx = version): the parent pushed on the base as a new version. Like ts_stack_merge, it joins
# the first other live head in the same state at the same position (edx = 1), else eax = a new
# stack node for it (edx = 0). Clobbers caller-saved registers.
.Lrf_place:
	mov r8, qword ptr [r15+C_SN]
	mov r9, qword ptr [r15+C_HEADS]
	xor esi, esi
5:	cmp esi, dword ptr [r15+C_NH]
	jae 7f
	cmp esi, ebx
	je 6f
	cmp dword ptr [r9 + rsi*8 + H_DEAD], 0
	jne 6f
	mov r10d, dword ptr [r9 + rsi*8 + H_NODE]
	lea r10, [r10+r10*2]
	cmp r13d, dword ptr [r8 + r10*8 + SN_POS]
	jne 6f
	cmp dx, word ptr [r8 + r10*8 + SN_STATE]
	jne 6f
	mov edi, dword ptr [r9 + rsi*8 + H_NODE]   # its one link joins that head, so no node is needed
	mov esi, ecx
	mov edx, r12d
	call p_add_link
	mov edx, 1
	ret
6:	inc esi
	jmp 5b
7:	mov eax, dword ptr [r15+C_SFREE]
	test eax, eax
	jz 3f
	lea r11, [rax+rax*2]
	mov r11d, dword ptr [r8 + r11*8 + SN_L0]
	mov dword ptr [r15+C_SFREE], r11d
	jmp 4f
3:	call p_snode_slow                   # the base stays reachable from the version's head
	mov r8, qword ptr [r15+C_SN]
4:	lea r11, [rax+rax*2]
	lea r11, [r8 + r11*8]
	or edx, 0x10000
	mov dword ptr [r11+SN_STATE], edx
	mov dword ptr [r11+SN_DYN], edi
	mov dword ptr [r11+SN_L0], ecx
	mov dword ptr [r11+SN_L0T], r12d
	mov dword ptr [r11+SN_POS], r13d
	mov dword ptr [r11+SN_EXT], 0
	xor edx, edx
	ret
.Lrf_ret:
	add rsp, 96
	pop r14
	pop r13
	pop r12
	pop rbp
	pop rbx
	ret

# p_pop(edi = version, esi = goal, or -1 for every path to the base): stack__iter with
# pop_count_callback or pop_all_callback. Up to 64 iterators walk the paths from the version's
# head; each keeps its subtrees as a list of cells (tree, previous cell), so a fork copies one
# index. An iterator that reaches its goal becomes a slice: its subtrees go to C_SLK bottom first,
# grouped with earlier slices that stopped at the same node (ts_stack__add_slice).
p_pop:
	push rbx
	push rbp
	push r12
	push r13
	push r14
	mov r12d, edi
	mov r13d, esi
	xor eax, eax
	mov dword ptr [r15+C_NSL], eax
	mov dword ptr [r15+C_NSLK], eax
	mov dword ptr [r15+C_NCELL], 1
	mov rax, qword ptr [r15+C_HEADS]
	mov eax, dword ptr [rax + r12*8 + H_NODE]
	mov dword ptr [r15+C_ITERS+IT_NODE], eax
	mov qword ptr [r15+C_ITERS+IT_COUNT], 0     # and IT_CELL
	mov dword ptr [r15+C_NI], 1
.Lpo_round:
	mov ebp, dword ptr [r15+C_NI]
	test ebp, ebp
	jz .Lpo_done
	xor ebx, ebx
.Lpo_it:
	cmp ebx, ebp
	jae .Lpo_round
	sub qword ptr [r15+C_STEPS], 1
	jb p_limit
	mov eax, ebx
	shl eax, 4
	lea r14, [r15 + C_ITERS + rax]
	mov ecx, dword ptr [r14+IT_NODE]
	lea rax, [rcx+rcx*2]
	shl rax, 3
	add rax, qword ptr [r15+C_SN]
	movzx edx, byte ptr [rax+SN_NL]
	test r13d, r13d
	js 1f
	cmp dword ptr [r14+IT_COUNT], r13d
	je .Lpo_pop
	test edx, edx
	jnz .Lpo_follow
	jmp .Lpo_stop
1:	test edx, edx
	jnz .Lpo_follow
.Lpo_pop:
	mov edi, ecx
	mov esi, dword ptr [r14+IT_CELL]
	call p_pop_slice
.Lpo_stop:
	dec ebp
	mov eax, dword ptr [r15+C_NI]
	dec eax
	mov dword ptr [r15+C_NI], eax
	mov ecx, ebx
2:	cmp ecx, eax
	jae .Lpo_it
	mov edx, ecx
	shl edx, 4
	movdqu xmm0, xmmword ptr [r15 + C_ITERS + rdx + 16]
	movdqu xmmword ptr [r15 + C_ITERS + rdx], xmm0
	inc ecx
	jmp 2b
.Lpo_follow:
	mov r8d, 1                          # links 1.. fork new iterators first
3:	cmp r8d, edx
	jae 4f
	mov eax, dword ptr [r15+C_NI]
	cmp eax, MAXITERS
	jae 5f
	inc dword ptr [r15+C_NI]
	shl eax, 4
	lea r9, [r15 + C_ITERS + rax]
	movdqu xmm0, xmmword ptr [r14]
	movdqu xmmword ptr [r9], xmm0
	mov edi, ecx
	mov esi, r8d
	call p_link_addr
	call .Lpo_step
5:	inc r8d
	jmp 3b
4:	lea rax, [rcx+rcx*2]                # link 0 moves this iterator
	shl rax, 3
	add rax, qword ptr [r15+C_SN]
	add rax, SN_L0
	mov r9, r14
	call .Lpo_step
	inc ebx
	jmp .Lpo_it
.Lpo_done:
	pop r14
	pop r13
	pop r12
	pop rbp
	pop rbx
	ret
# .Lpo_step(r9 = iterator, rax = link): follow it, prepending its tree to the iterator's list
# and counting it unless extra. Clobbers rax, rsi, rdi, r10, r11.
.Lpo_step:
	mov r10d, dword ptr [rax]
	mov r11d, dword ptr [rax+4]
	mov dword ptr [r9+IT_NODE], r10d
	mov esi, dword ptr [r15+C_NCELL]
	cmp esi, dword ptr [r15+C_CELLCAP]
	jb 1f
	push rcx
	push rsi
	lea rdi, [r15+C_CELLS]
	inc esi
	mov ecx, 8
	call p_grow
	pop rsi
	pop rcx
1:	mov rdi, qword ptr [r15+C_CELLS]
	mov dword ptr [rdi + rsi*8], r11d
	mov eax, dword ptr [r9+IT_CELL]
	mov dword ptr [rdi + rsi*8 + 4], eax
	mov dword ptr [r9+IT_CELL], esi
	inc esi
	mov dword ptr [r15+C_NCELL], esi
	mov rdi, qword ptr [r15+C_NODES]
	TREE_OFF r11
	cmp byte ptr [rdi + r11 + N_EXTRA], 0
	jne 2f
	inc dword ptr [r9+IT_COUNT]
2:	ret

# p_pop_slice(edi = stack node, esi = cell list): store the list as a slice, bottom first, and
# file it after the last slice that stopped at the same node, or under a new version.
p_pop_slice:
	push rbx
	push r12
	push r13
	mov r12d, edi
	mov rcx, qword ptr [r15+C_CELLS]
	xor edx, edx                        # length
	mov eax, esi
1:	test eax, eax
	jz 2f
	inc edx
	mov eax, dword ptr [rcx + rax*8 + 4]
	jmp 1b
2:	mov eax, edx                        # a work unit per 16 subtrees
	shr eax, 4
	sub qword ptr [r15+C_STEPS], rax
	jb p_limit
	mov r13d, dword ptr [r15+C_NSLK]
	lea ebx, [r13 + rdx]
	cmp ebx, dword ptr [r15+C_SLKCAP]
	jbe 3f
	push rsi
	push rdx
	lea rdi, [r15+C_SLK]
	mov esi, ebx
	mov ecx, 4
	call p_grow
	pop rdx
	pop rsi
3:	mov dword ptr [r15+C_NSLK], ebx
	mov rcx, qword ptr [r15+C_CELLS]
	mov rdi, qword ptr [r15+C_SLK]
	mov ebx, r13d
	mov eax, esi
4:	test eax, eax                       # the newest cell holds the bottom tree
	jz 5f
	mov r8d, dword ptr [rcx + rax*8]
	mov dword ptr [rdi + rbx*4], r8d
	inc ebx
	mov eax, dword ptr [rcx + rax*8 + 4]
	jmp 4b
5:	mov ebx, edx                        # length
	mov ecx, dword ptr [r15+C_NSL]
	lea esi, [rcx+1]
	cmp esi, dword ptr [r15+C_SLCAP]
	jbe 6f
	lea rdi, [r15+C_SLICES]
	push rcx
	mov ecx, 16
	call p_grow
	pop rcx
6:	mov r8, qword ptr [r15+C_SLICES]
	mov r9, qword ptr [r15+C_HEADS]
7:	test ecx, ecx
	jz .Lps_new
	dec ecx
	mov eax, ecx
	shl eax, 4
	mov eax, dword ptr [r8 + rax + SL_VER]
	cmp dword ptr [r9 + rax*8 + H_NODE], r12d
	jne 7b
	inc ecx                             # insert at ecx under version eax
	mov edx, dword ptr [r15+C_NSL]
8:	cmp edx, ecx
	jbe .Lps_put
	mov esi, edx
	shl esi, 4
	movdqu xmm0, xmmword ptr [r8 + rsi - 16]
	movdqu xmmword ptr [r8 + rsi], xmm0
	dec edx
	jmp 8b
.Lps_new:
	mov edi, r12d
	call p_add_version
	mov ecx, dword ptr [r15+C_NSL]
.Lps_put:
	shl ecx, 4
	mov dword ptr [r8 + rcx + SL_VER], eax
	mov dword ptr [r8 + rcx + SL_OFF], r13d
	mov dword ptr [r8 + rcx + SL_LEN], ebx
	inc dword ptr [r15+C_NSL]
	pop r13
	pop r12
	pop rbx
	ret

# p_add_version(edi = stack node) -> eax = new active version at the end. Preserves the rest.
p_add_version:
	mov eax, dword ptr [r15+C_NH]
	push rsi
	push rcx
	lea esi, [rax+1]
	cmp esi, dword ptr [r15+C_HCAP]
	jbe 1f
	push rdi
	lea rdi, [r15+C_HEADS]
	mov ecx, 8
	call p_grow
	pop rdi
1:	mov rcx, qword ptr [r15+C_HEADS]
	mov dword ptr [rcx + rax*8 + H_NODE], edi
	mov dword ptr [rcx + rax*8 + H_DEAD], 0
	inc dword ptr [r15+C_NH]
	pop rcx
	pop rsi
	ret

# p_remove_version(edi = version). Clobbers rax, rcx, rdx, rdi.
p_remove_version:
	mov edi, edi
	mov eax, dword ptr [r15+C_NH]
	dec eax
	mov dword ptr [r15+C_NH], eax
	mov rcx, qword ptr [r15+C_HEADS]
1:	cmp edi, eax
	jae 2f
	mov rdx, qword ptr [rcx + rdi*8 + 8]
	mov qword ptr [rcx + rdi*8], rdx
	inc edi
	jmp 1b
2:	ret

# p_renumber(edi = v1, esi = v2 < v1): v1's head replaces v2's. Clobbers rax, rcx, rdx, rdi.
p_renumber:
	mov edi, edi
	mov esi, esi
	mov rcx, qword ptr [r15+C_HEADS]
	mov rax, qword ptr [rcx + rdi*8]
	mov qword ptr [rcx + rsi*8], rax
	jmp p_remove_version

# p_link_equiv(edi = node a, esi = tree a, edx = node b, ecx = tree b) -> eax:
# stack__subtree_is_equivalent (padding is the tree's start minus its predecessor's position).
# Clobbers rcx, rdx, rsi, rdi, r8-r11.
p_link_equiv:
	mov eax, 1
	cmp esi, ecx
	je 9f
	xor eax, eax
	mov r8, qword ptr [r15+C_NODES]
	TREE_OFF rsi
	add rsi, r8
	TREE_OFF rcx
	add rcx, r8
	mov r9d, dword ptr [rsi+N_SYM]
	mov r10d, dword ptr [rcx+N_SYM]
	cmp r9w, r10w
	jne 9f
	shr r9d, 24
	shr r10d, 24
	cmp r9d, r10d
	jne 9f
	mov r9d, dword ptr [rsi+N_CC]
	cmp r9d, dword ptr [rcx+N_CC]
	jne 9f
	mov r9d, dword ptr [rsi+N_END]
	sub r9d, dword ptr [rsi+N_START]
	mov r10d, dword ptr [rcx+N_END]
	sub r10d, dword ptr [rcx+N_START]
	cmp r9d, r10d
	jne 9f
	mov r11, qword ptr [r15+C_SN]
	lea r8, [rdi+rdi*2]
	mov r9d, dword ptr [rsi+N_START]
	sub r9d, dword ptr [r11 + r8*8 + SN_POS]
	lea r8, [rdx+rdx*2]
	mov r10d, dword ptr [rcx+N_START]
	sub r10d, dword ptr [r11 + r8*8 + SN_POS]
	cmp r9d, r10d
	jne 9f
	mov eax, 1
9:	ret

# ---------------------------------------------------------------------------
# p_subtree_compare(edi = a, esi = b) -> eax in {-1, 0, 1}
# ts_subtree_compare: pre-order comparison of (symbol, child count). Iterative over the frame
# stack so deep trees cannot overflow the native stack; each visited pair costs one work unit.
# ---------------------------------------------------------------------------
p_subtree_compare:
	push rbx
	push rbp
	push r12
	push r13
	push r14
	mov r12d, edi
	mov r13d, esi
	mov r8, qword ptr [r15+C_NODES]
	mov r9, qword ptr [r15+C_KIDS]
	mov rbx, qword ptr [r15+C_ESTK]
	xor ebp, ebp                        # frames on the stack
	jmp .Lsc_visit
.Lsc_loop:
	test ebp, ebp
	jz .Lsc_eq
	dec ebp
	mov eax, ebp
	shl eax, 4
	mov r12d, dword ptr [rbx + rax]
	mov r13d, dword ptr [rbx + rax + 4]
.Lsc_visit:
	sub qword ptr [r15+C_STEPS], 1
	jb p_limit
	mov eax, r12d
	TREE_OFF rax
	lea r10, [r8 + rax]
	mov eax, r13d
	TREE_OFF rax
	lea r11, [r8 + rax]
	movzx eax, word ptr [r10+N_SYM]
	movzx ecx, word ptr [r11+N_SYM]
	cmp eax, ecx
	jb .Lsc_m1
	ja .Lsc_p1
	mov ecx, dword ptr [r10+N_CC]
	cmp ecx, dword ptr [r11+N_CC]
	jb .Lsc_m1
	ja .Lsc_p1
	test ecx, ecx
	jz .Lsc_loop
	lea esi, [rbp + rcx]
	cmp esi, dword ptr [r15+C_ESTKCAP]
	jbe 1f
	call p_grow_estk
	mov rbx, qword ptr [r15+C_ESTK]
1:	mov edi, dword ptr [r10+N_CI]
	mov edx, dword ptr [r11+N_CI]
2:	dec ecx                             # push child pairs last-first so child 0 pops first
	mov r14d, ebp
	shl r14d, 4
	lea eax, [rdi + rcx]
	mov eax, dword ptr [r9 + rax*4]
	mov dword ptr [rbx + r14], eax
	lea eax, [rdx + rcx]
	mov eax, dword ptr [r9 + rax*4]
	mov dword ptr [rbx + r14 + 4], eax
	inc ebp
	test ecx, ecx
	jnz 2b
	jmp .Lsc_loop
.Lsc_eq:
	xor eax, eax
	jmp .Lsc_ret
.Lsc_m1:
	mov eax, -1
	jmp .Lsc_ret
.Lsc_p1:
	mov eax, 1
.Lsc_ret:
	pop r14
	pop r13
	pop r12
	pop rbp
	pop rbx
	ret


# p_add_link(edi = node, esi = link node, edx = link tree): stack_node_add_link. Its recursion
# (merging the links of two mergeable predecessors) runs on 32-byte frames in the frame buffer, so
# depth cannot overflow the native stack. Each call costs a work unit.
p_add_link:
	push rbx
	push rbp
	push r12
	push r13
	push r14
	sub rsp, 16                         # [rsp] = depth
	mov dword ptr [rsp], 0
	mov r12d, edi                       # self
	mov r13d, esi                       # link node
	mov r14d, edx                       # link tree
.Lal_call:
	sub qword ptr [r15+C_STEPS], 1
	jb p_limit
	cmp r13d, r12d
	je .Lal_ret
	xor ebp, ebp                        # i over self's links
.Lal_scan:
	mov eax, r12d
	lea rax, [rax+rax*2]
	mov rcx, qword ptr [r15+C_SN]
	movzx eax, byte ptr [rcx + rax*8 + SN_NL]
	cmp ebp, eax
	jae .Lal_append
	mov edi, r12d
	mov esi, ebp
	call p_link_addr
	mov ebx, dword ptr [rax]            # existing link's node
	mov edi, ebx
	mov esi, dword ptr [rax+4]
	mov edx, r13d
	mov ecx, r14d
	call p_link_equiv
	test eax, eax
	jz .Lal_snext
	cmp ebx, r13d
	jne .Lal_mergeable
	mov edi, r12d                       # the same two nodes: keep the higher-precedence subtree
	mov esi, ebp
	call p_link_addr
	mov r8, qword ptr [r15+C_NODES]
	mov ecx, dword ptr [rax+4]
	TREE_OFF rcx
	mov edx, r14d
	TREE_OFF rdx
	mov ecx, dword ptr [r8 + rcx + N_DYN]
	mov edx, dword ptr [r8 + rdx + N_DYN]
	cmp edx, ecx
	jle .Lal_ret
	mov dword ptr [rax+4], r14d
	mov r9, qword ptr [r15+C_SN]
	mov eax, r13d
	lea rax, [rax+rax*2]
	add edx, dword ptr [r9 + rax*8 + SN_DYN]
	mov eax, r12d
	lea rax, [rax+rax*2]
	mov dword ptr [r9 + rax*8 + SN_DYN], edx
	jmp .Lal_ret
.Lal_mergeable:
	mov r9, qword ptr [r15+C_SN]
	mov eax, ebx
	lea rax, [rax+rax*2]
	lea rax, [r9 + rax*8]
	mov ecx, r13d
	lea rcx, [rcx+rcx*2]
	lea rcx, [r9 + rcx*8]
	mov edx, dword ptr [rax+SN_POS]
	cmp edx, dword ptr [rcx+SN_POS]
	jne .Lal_snext
	mov dx, word ptr [rax+SN_STATE]
	cmp dx, word ptr [rcx+SN_STATE]
	jne .Lal_snext
	xor ebp, ebp                        # j over the link node's links, added to the existing node
.Lal_rloop:
	mov eax, r13d
	lea rax, [rax+rax*2]
	mov rcx, qword ptr [r15+C_SN]
	movzx eax, byte ptr [rcx + rax*8 + SN_NL]
	cmp ebp, eax
	jae .Lal_rdone
	mov eax, dword ptr [rsp]
	lea esi, [rax*2 + 2]
	cmp esi, dword ptr [r15+C_ESTKCAP]
	jbe 1f
	call p_grow_estk
1:	mov rcx, qword ptr [r15+C_ESTK]
	shl eax, 5
	mov dword ptr [rcx + rax], r12d
	mov dword ptr [rcx + rax + 4], r13d
	mov dword ptr [rcx + rax + 8], r14d
	mov dword ptr [rcx + rax + 12], ebx
	mov dword ptr [rcx + rax + 16], ebp
	inc dword ptr [rsp]
	mov edi, r13d
	mov esi, ebp
	call p_link_addr
	mov r12d, ebx
	mov r13d, dword ptr [rax]
	mov r14d, dword ptr [rax+4]
	jmp .Lal_call
.Lal_snext:
	inc ebp
	jmp .Lal_scan
.Lal_append:
	cmp eax, MAXLINKS
	jae .Lal_ret
	mov ebp, eax
	cmp eax, 1
	jne 2f
	call p_ext_new
	mov ecx, r12d
	lea rcx, [rcx+rcx*2]
	mov rdx, qword ptr [r15+C_SN]
	mov dword ptr [rdx + rcx*8 + SN_EXT], eax
2:	mov edi, r12d
	mov esi, ebp
	call p_link_addr
	mov dword ptr [rax], r13d
	mov dword ptr [rax+4], r14d
	mov ecx, r12d
	lea rcx, [rcx+rcx*2]
	mov rdx, qword ptr [r15+C_SN]
	inc byte ptr [rdx + rcx*8 + SN_NL]
.Lal_rdone:                             # self's precedence = max(self, link node + link tree)
	mov r8, qword ptr [r15+C_NODES]
	mov r9, qword ptr [r15+C_SN]
	mov eax, r14d
	TREE_OFF rax
	mov edx, dword ptr [r8 + rax + N_DYN]
	mov eax, r13d
	lea rax, [rax+rax*2]
	add edx, dword ptr [r9 + rax*8 + SN_DYN]
	mov eax, r12d
	lea rax, [rax+rax*2]
	cmp edx, dword ptr [r9 + rax*8 + SN_DYN]
	jle .Lal_ret
	mov dword ptr [r9 + rax*8 + SN_DYN], edx
.Lal_ret:
	mov eax, dword ptr [rsp]
	test eax, eax
	jz .Lal_exit
	dec eax
	mov dword ptr [rsp], eax
	shl eax, 5
	mov rcx, qword ptr [r15+C_ESTK]
	mov r12d, dword ptr [rcx + rax]
	mov r13d, dword ptr [rcx + rax + 4]
	mov r14d, dword ptr [rcx + rax + 8]
	mov ebx, dword ptr [rcx + rax + 12]
	mov ebp, dword ptr [rcx + rax + 16]
	inc ebp
	jmp .Lal_rloop
.Lal_exit:
	add rsp, 16
	pop r14
	pop r13
	pop r12
	pop rbp
	pop rbx
	ret

# p_merge(edi = a, esi = b) -> eax: ts_stack_merge. If both versions are live with heads in the
# same state at the same position, b's head links join a's head and b is removed.
p_merge:
	push rbx
	push rbp
	push r12
	push r13
	mov r12d, edi
	mov r13d, esi
	mov rcx, qword ptr [r15+C_HEADS]
	xor eax, eax
	cmp dword ptr [rcx + r12*8 + H_DEAD], 0
	jne 9f
	cmp dword ptr [rcx + r13*8 + H_DEAD], 0
	jne 9f
	mov edx, dword ptr [rcx + r12*8 + H_NODE]
	mov esi, dword ptr [rcx + r13*8 + H_NODE]
	mov r8, qword ptr [r15+C_SN]
	lea rdx, [rdx+rdx*2]
	lea rsi, [rsi+rsi*2]
	mov edi, dword ptr [r8 + rdx*8 + SN_POS]
	cmp edi, dword ptr [r8 + rsi*8 + SN_POS]
	jne 9f
	mov di, word ptr [r8 + rdx*8 + SN_STATE]
	cmp di, word ptr [r8 + rsi*8 + SN_STATE]
	jne 9f
	xor ebp, ebp
1:	mov rcx, qword ptr [r15+C_HEADS]
	mov ebx, dword ptr [rcx + r13*8 + H_NODE]
	mov eax, ebx
	lea rax, [rax+rax*2]
	mov rdx, qword ptr [r15+C_SN]
	movzx eax, byte ptr [rdx + rax*8 + SN_NL]
	cmp ebp, eax
	jae 2f
	mov edi, ebx
	mov esi, ebp
	call p_link_addr
	mov esi, dword ptr [rax]
	mov edx, dword ptr [rax+4]
	mov rcx, qword ptr [r15+C_HEADS]
	mov edi, dword ptr [rcx + r12*8 + H_NODE]
	call p_add_link
	inc ebp
	jmp 1b
2:	mov edi, r13d
	call p_remove_version
	mov eax, 1
9:	pop r13
	pop r12
	pop rbp
	pop rbx
	ret

# p_strip(edi = offset, esi = length) -> eax = the slice's length without its trailing extras.
# Clobbers rcx, rdx, r8.
p_strip:
	mov eax, esi
	mov rcx, qword ptr [r15+C_SLK]
	mov r8, qword ptr [r15+C_NODES]
1:	test eax, eax
	jz 2f
	lea edx, [rdi + rax - 1]
	mov edx, dword ptr [rcx + rdx*4]
	TREE_OFF rdx
	cmp byte ptr [r8 + rdx + N_EXTRA], 0
	je 2f
	dec eax
	jmp 1b
2:	ret

# p_build(edi = offset, esi = count, edx = base position, rcx = reduce action) -> eax = tree:
# ts_subtree_new_node over C_SLK[offset..offset+count). Its precedence is the children's sum.
p_build:
	push rbx
	push r12
	mov r12, rcx
	mov ebx, edx
	mov eax, dword ptr [r15+C_NK]
	add eax, esi
	cmp eax, dword ptr [r15+C_KCAP]
	jbe 1f
	push rdi
	mov edi, esi
	call p_grow_kids
	pop rdi
1:	ALLOC_NODE eax
	mov r8, qword ptr [r15+C_NODES]
	mov r9d, eax
	TREE_OFF r9
	add r9, r8
	mov rcx, r12
	shr rcx, 16
	movzx edx, cx
	shr rcx, 16
	movzx ecx, cl
	shl ecx, 16
	or ecx, edx
	mov dword ptr [r9+N_SYM], ecx
	mov dword ptr [r9+N_CC], esi
	mov r10, qword ptr [r15+C_KIDS]
	mov r11d, dword ptr [r15+C_NK]
	mov dword ptr [r9+N_CI], r11d
	mov rcx, qword ptr [r15+C_SLK]
	xor edx, edx
	test esi, esi
	jz 3f
2:	mov r12d, dword ptr [rcx + rdi*4]
	mov dword ptr [r10 + r11*4], r12d
	TREE_OFF r12
	add edx, dword ptr [r8 + r12 + N_DYN]
	inc edi
	inc r11d
	dec esi
	jnz 2b
	mov dword ptr [r9+N_DYN], edx
	mov dword ptr [r15+C_NK], r11d
	mov ecx, dword ptr [r9+N_CI]
	mov ecx, dword ptr [r10 + rcx*4]
	TREE_OFF rcx
	mov ecx, dword ptr [r8 + rcx + N_START]
	mov dword ptr [r9+N_START], ecx
	mov ecx, dword ptr [r10 + r11*4 - 4]
	TREE_OFF rcx
	mov ecx, dword ptr [r8 + rcx + N_END]
	mov dword ptr [r9+N_END], ecx
	jmp 4f
3:	mov dword ptr [r9+N_DYN], 0
	mov dword ptr [r9+N_START], ebx
	mov dword ptr [r9+N_END], ebx
4:	pop r12
	pop rbx
	ret

# p_select(edi = left tree, esi = offset, edx = count) -> eax = 1 to take the alternative
# children C_SLK[offset..offset+count) instead: ts_parser__select_children with no error costs.
p_select:
	push rbx
	push rbp
	push r12
	push r13
	push r14
	mov r12d, edi
	mov r13d, esi
	mov r14d, edx
	mov rcx, qword ptr [r15+C_SLK]
	mov r8, qword ptr [r15+C_NODES]
	xor eax, eax                        # the alternative's precedence
	xor ebx, ebx
1:	cmp ebx, r14d
	jae 2f
	lea edx, [r13 + rbx]
	mov edx, dword ptr [rcx + rdx*4]
	TREE_OFF rdx
	add eax, dword ptr [r8 + rdx + N_DYN]
	inc ebx
	jmp 1b
2:	mov edx, r12d
	TREE_OFF rdx
	add rdx, r8
	cmp eax, dword ptr [rdx+N_DYN]
	jg .Lse_right
	jl .Lse_left
	mov ecx, dword ptr [rdx+N_CC]       # ts_subtree_compare(left, scratch node of the same symbol)
	cmp ecx, r14d
	jb .Lse_left
	ja .Lse_right
	mov ebp, dword ptr [rdx+N_CI]
	xor ebx, ebx
3:	cmp ebx, r14d
	jae .Lse_left
	mov rcx, qword ptr [r15+C_KIDS]
	lea eax, [rbp + rbx]
	mov edi, dword ptr [rcx + rax*4]
	mov rcx, qword ptr [r15+C_SLK]
	lea eax, [r13 + rbx]
	mov esi, dword ptr [rcx + rax*4]
	call p_subtree_compare
	test eax, eax
	jg .Lse_right
	jl .Lse_left
	inc ebx
	jmp 3b
.Lse_right:
	mov eax, 1
	jmp 4f
.Lse_left:
	xor eax, eax
4:	pop r14
	pop r13
	pop r12
	pop rbp
	pop rbx
	ret

# p_reduce_gss(edi = version, rsi = reduce action) -> eax = the first new version, or -1 if the
# reduce made none (every result merged into an earlier version): ts_parser__reduce.
	.set RG_INIT, 0
	.set RG_SLVER, 4
	.set RG_SV, 8
	.set RG_BOFF, 12
	.set RG_BN, 16
	.set RG_BLEN, 20
	.set RG_BASEPOS, 24
	.set RG_AOFF, 28
	.set RG_AN, 32
	.set RG_ALEN, 36
	.set RG_NEXT, 40
p_reduce_gss:
	push rbx
	push rbp
	push r12
	push r13
	push r14
	sub rsp, 48
	mov r12d, edi
	mov r13, rsi
	mov eax, dword ptr [r15+C_NH]
	mov dword ptr [rsp+RG_INIT], eax
	mov esi, r13d
	shr esi, 8
	movzx esi, sil
	call p_pop
	xor ebp, ebp                        # versions removed so far
	xor ebx, ebx                        # slice
.Lrg_slice:
	cmp ebx, dword ptr [r15+C_NSL]
	jae .Lrg_done
	mov rax, qword ptr [r15+C_SLICES]
	mov ecx, ebx
	shl ecx, 4
	mov edx, dword ptr [rax + rcx + SL_VER]
	mov dword ptr [rsp+RG_SLVER], edx
	sub edx, ebp
	mov dword ptr [rsp+RG_SV], edx
	cmp edx, MAXSLICEVER
	jbe .Lrg_keep
	mov edi, edx                        # too many versions: drop this one and its other slices
	call p_remove_version
	inc ebp
1:	lea eax, [rbx+1]
	cmp eax, dword ptr [r15+C_NSL]
	jae 2f
	mov rcx, qword ptr [r15+C_SLICES]
	shl eax, 4
	mov eax, dword ptr [rcx + rax + SL_VER]
	cmp eax, dword ptr [rsp+RG_SLVER]
	jne 2f
	inc ebx
	jmp 1b
2:	inc ebx
	jmp .Lrg_slice
.Lrg_keep:
	mov edi, dword ptr [rax + rcx + SL_OFF]
	mov esi, dword ptr [rax + rcx + SL_LEN]
	mov dword ptr [rsp+RG_BOFF], edi
	mov dword ptr [rsp+RG_BLEN], esi
	call p_strip
	mov dword ptr [rsp+RG_BN], eax
	mov rcx, qword ptr [r15+C_HEADS]
	mov edx, dword ptr [rsp+RG_SV]
	mov edx, dword ptr [rcx + rdx*8 + H_NODE]
	lea rdx, [rdx+rdx*2]
	mov rcx, qword ptr [r15+C_SN]
	mov edx, dword ptr [rcx + rdx*8 + SN_POS]
	mov dword ptr [rsp+RG_BASEPOS], edx
	mov edi, dword ptr [rsp+RG_BOFF]
	mov esi, eax
	mov rcx, r13
	call p_build
	mov r14d, eax
.Lrg_alt:                               # further slices that stopped at the same node
	lea eax, [rbx+1]
	cmp eax, dword ptr [r15+C_NSL]
	jae .Lrg_push
	mov rcx, qword ptr [r15+C_SLICES]
	shl eax, 4
	mov edx, dword ptr [rcx + rax + SL_VER]
	cmp edx, dword ptr [rsp+RG_SLVER]
	jne .Lrg_push
	inc ebx
	mov edi, dword ptr [rcx + rax + SL_OFF]
	mov esi, dword ptr [rcx + rax + SL_LEN]
	mov dword ptr [rsp+RG_AOFF], edi
	mov dword ptr [rsp+RG_ALEN], esi
	call p_strip
	mov dword ptr [rsp+RG_AN], eax
	mov edi, r14d
	mov esi, dword ptr [rsp+RG_AOFF]
	mov edx, eax
	call p_select
	test eax, eax
	jz .Lrg_alt
	mov edi, dword ptr [rsp+RG_AOFF]
	mov esi, dword ptr [rsp+RG_AN]
	mov edx, dword ptr [rsp+RG_BASEPOS]
	mov rcx, r13
	call p_build
	mov r14d, eax
	mov eax, dword ptr [rsp+RG_AOFF]
	mov dword ptr [rsp+RG_BOFF], eax
	mov eax, dword ptr [rsp+RG_AN]
	mov dword ptr [rsp+RG_BN], eax
	mov eax, dword ptr [rsp+RG_ALEN]
	mov dword ptr [rsp+RG_BLEN], eax
	jmp .Lrg_alt
.Lrg_push:
	mov rax, qword ptr [r15+C_NODES]
	mov ecx, r14d
	TREE_OFF rcx
	cmp dword ptr [rax + rcx + N_CC], 0
	je 3f
	mov rdx, r13
	sar rdx, 48
	add dword ptr [rax + rcx + N_DYN], edx
3:	mov rcx, qword ptr [r15+C_HEADS]
	mov edx, dword ptr [rsp+RG_SV]
	mov edx, dword ptr [rcx + rdx*8 + H_NODE]
	lea rdx, [rdx+rdx*2]
	mov rcx, qword ptr [r15+C_SN]
	movzx ecx, word ptr [rcx + rdx*8 + SN_STATE]
	imul ecx, dword ptr [r15+C_LANG+L_NSYM]
	mov rdx, r13
	shr rdx, 16
	movzx edx, dx
	add ecx, edx
	mov rdx, qword ptr [r15+C_LANG+L_PARSE_TABLE]
	movzx ecx, word ptr [rdx + rcx*2]
	mov dword ptr [rsp+RG_NEXT], ecx
	mov edi, dword ptr [rsp+RG_SV]
	mov esi, r14d
	mov edx, ecx
	call p_push
	mov r14d, dword ptr [rsp+RG_BN]     # trailing extras
4:	cmp r14d, dword ptr [rsp+RG_BLEN]
	jae 5f
	mov rax, qword ptr [r15+C_SLK]
	mov ecx, dword ptr [rsp+RG_BOFF]
	add ecx, r14d
	mov esi, dword ptr [rax + rcx*4]
	mov edi, dword ptr [rsp+RG_SV]
	mov edx, dword ptr [rsp+RG_NEXT]
	call p_push
	inc r14d
	jmp 4b
5:	xor r14d, r14d                      # merge into the first earlier version that accepts it
6:	cmp r14d, dword ptr [rsp+RG_SV]
	jae 7f
	cmp r14d, r12d
	je 8f
	mov edi, r14d
	mov esi, dword ptr [rsp+RG_SV]
	call p_merge
	test eax, eax
	jz 8f
	inc ebp
	jmp 7f
8:	inc r14d
	jmp 6b
7:	inc ebx
	jmp .Lrg_slice
.Lrg_done:
	mov eax, -1
	mov ecx, dword ptr [rsp+RG_INIT]
	cmp dword ptr [r15+C_NH], ecx
	cmova eax, ecx
	add rsp, 48
	pop r14
	pop r13
	pop r12
	pop rbp
	pop rbx
	ret

# p_accept(edi = version): ts_parser__accept. Push the eof leaf, pop every path to the base, build
# a root per path (the topmost non-extra tree's children spliced among the other trees) and keep
# the best against the finished tree.
p_accept:
	push rbx
	push rbp
	push r12
	push r13
	push r14
	mov r12d, edi
	mov esi, 1
	xor edx, edx
	mov ecx, 1
	call p_shift
	mov edi, r12d
	mov esi, -1
	call p_pop
	xor ebx, ebx
.Lac_slice:
	cmp ebx, dword ptr [r15+C_NSL]
	jae .Lac_end
	mov rax, qword ptr [r15+C_SLICES]
	mov ecx, ebx
	shl ecx, 4
	mov r13d, dword ptr [rax + rcx + SL_OFF]
	mov r14d, dword ptr [rax + rcx + SL_LEN]
	mov rcx, qword ptr [r15+C_SLK]
	mov r8, qword ptr [r15+C_NODES]
	mov ebp, r14d
1:	test ebp, ebp
	jz .Lac_next
	dec ebp
	lea eax, [r13 + rbp]
	mov eax, dword ptr [rcx + rax*4]
	mov rdx, rax
	TREE_OFF rdx
	cmp byte ptr [r8 + rdx + N_EXTRA], 0
	jne 1b
	push rax                            # the old root
	push rax
	mov edi, dword ptr [r8 + rdx + N_CC]
	lea edi, [rdi + r14 - 1]            # children of the new root
	mov eax, dword ptr [r15+C_NK]
	add eax, edi
	cmp eax, dword ptr [r15+C_KCAP]
	jbe 2f
	call p_grow_kids
2:	ALLOC_NODE eax
	pop rdx
	pop rdx
	mov r8, qword ptr [r15+C_NODES]
	mov r10, qword ptr [r15+C_KIDS]
	mov rcx, qword ptr [r15+C_SLK]
	mov r11d, dword ptr [r15+C_NK]
	xor r9d, r9d                        # precedence: the children's sum
	xor esi, esi
3:	cmp esi, ebp
	jae 4f
	lea edi, [r13 + rsi]
	mov edi, dword ptr [rcx + rdi*4]
	call .Lac_put
	inc esi
	jmp 3b
4:	mov rdi, rdx
	TREE_OFF rdi
	mov esi, dword ptr [r8 + rdi + N_CI]
	push rbx
	mov ebx, dword ptr [r8 + rdi + N_CC]
5:	test ebx, ebx
	jz 6f
	mov edi, dword ptr [r10 + rsi*4]
	call .Lac_put
	inc esi
	dec ebx
	jmp 5b
6:	pop rbx
	lea esi, [rbp+1]
7:	cmp esi, r14d
	jae 8f
	lea edi, [r13 + rsi]
	mov edi, dword ptr [rcx + rdi*4]
	call .Lac_put
	inc esi
	jmp 7b
8:	mov rdi, rax
	TREE_OFF rdi
	add rdi, r8                         # new root
	TREE_OFF rdx
	mov esi, dword ptr [r8 + rdx + N_SYM]
	and esi, 0xFFFFFF                   # symbol and production id, not extra
	mov dword ptr [rdi+N_SYM], esi
	mov esi, dword ptr [r15+C_NK]
	mov dword ptr [rdi+N_CI], esi
	mov edx, r11d
	sub edx, esi
	mov dword ptr [rdi+N_CC], edx
	mov dword ptr [rdi+N_DYN], r9d
	mov edx, dword ptr [r10 + rsi*4]
	TREE_OFF rdx
	mov edx, dword ptr [r8 + rdx + N_START]
	mov dword ptr [rdi+N_START], edx
	mov edx, dword ptr [r10 + r11*4 - 4]
	TREE_OFF rdx
	mov edx, dword ptr [r8 + rdx + N_END]
	mov dword ptr [rdi+N_END], edx
	mov dword ptr [r15+C_NK], r11d
	mov ecx, dword ptr [r15+C_FINISHED] # ts_parser__select_tree(finished, root)
	test ecx, ecx
	js .Lac_take
	mov rdx, rcx
	TREE_OFF rdx
	cmp r9d, dword ptr [r8 + rdx + N_DYN]
	jg .Lac_take
	jl .Lac_next
	push rax
	push rax
	mov edi, ecx
	mov esi, eax
	call p_subtree_compare
	mov ecx, eax
	pop rax
	pop rax
	cmp ecx, 0
	jle .Lac_next
.Lac_take:
	mov dword ptr [r15+C_FINISHED], eax
.Lac_next:
	inc ebx
	jmp .Lac_slice
.Lac_end:
	mov rax, qword ptr [r15+C_SLICES]
	mov edi, dword ptr [rax+SL_VER]
	call p_remove_version
	mov rcx, qword ptr [r15+C_HEADS]
	mov dword ptr [rcx + r12*8 + H_DEAD], 1
	pop r14
	pop r13
	pop r12
	pop rbp
	pop rbx
	ret
# .Lac_put(edi = tree): append to the new root's children. Uses r8, r10, r11, r9. Clobbers rdi.
.Lac_put:
	mov dword ptr [r10 + r11*4], edi
	inc r11d
	TREE_OFF rdi
	add r9d, dword ptr [r8 + rdi + N_DYN]
	ret

# ---------------------------------------------------------------------------
# ADVANCE (ebx = version): lex (or reuse the cached token) and apply actions until a shift,
# accept or error. Mirrors ts_parser__advance. Expanded once, as the body of tsasm_parse's version
# loop, whose frame holds its locals: [rsp] = k, [rsp+4] = count, [rsp+8] = last reduction
# version, [rsp+12] = version. Clobbers every register but rbx and r15.
# ---------------------------------------------------------------------------
.macro ADVANCE
# r13d = the state of version ebx's head. Clobbers rax, rcx.
.macro HEAD_STATE_R13
	mov rax, qword ptr [r15+C_HEADS]
	mov eax, dword ptr [rax + rbx*8 + H_NODE]
	lea rax, [rax+rax*2]
	mov rcx, qword ptr [r15+C_SN]
	movzx r13d, word ptr [rcx + rax*8 + SN_STATE]
.endm
	sub qword ptr [r15+C_STEPS], 1
	jb p_limit
	mov rax, qword ptr [r15+C_HEADS]
	mov eax, dword ptr [rax + rbx*8 + H_NODE]
	lea rax, [rax+rax*2]
	shl rax, 3
	add rax, qword ptr [r15+C_SN]
	movzx r13d, word ptr [rax+SN_STATE]
	mov esi, dword ptr [rax+SN_POS]
	cmp dword ptr [r15+C_TOKVALID], 0
	je .Lad_lex
	cmp esi, dword ptr [r15+C_TPOS]
	jne .Lad_lex
	mov edi, r13d
	push rsi
	push rsi
	call p_can_reuse
	pop rsi
	pop rsi
	test eax, eax
	jnz .Lad_have
.Lad_lex:
	mov edi, r13d
	call p_lex
	test eax, eax
	jz .Lad_dead
.Lad_have:
	mov r14d, dword ptr [r15+C_TSYM]
.Lad_lookup:
	mov eax, r13d
	imul eax, dword ptr [r15+C_LANG+L_NSYM]
	add eax, r14d
	mov rdx, qword ptr [r15+C_LANG+L_PARSE_TABLE]
	movzx ebp, word ptr [rdx + rax*2]   # action index
.Lad_entry:
	mov rdx, qword ptr [r15+C_LANG+L_ACTIONS]
	mov rax, qword ptr [rdx + rbp*8]
	movzx ecx, al                       # count
	cmp ecx, 1
	jne .Lad_multi
	mov rsi, qword ptr [rdx + rbp*8 + 8]
	test esi, 3
	jnz .Lad_single_nonshift
	mov ecx, esi                        # shift
	shr ecx, 2
	and ecx, 1
	mov eax, esi
	shr eax, 16
	test ecx, ecx
	cmovnz eax, r13d
	mov edi, ebx
	mov esi, eax
	mov edx, r14d
	SHIFT_LEAF
	jmp .Lad_ret
.Lad_single_nonshift:
	mov eax, esi
	and eax, 3
	cmp eax, 1
	jne .Lad_acc_or_rec
	cmp dword ptr [r15+C_NH], MAXSLICEVER
	jb .Lad_inplace
.Lad_rslow:
	mov edi, ebx
	mov edx, 1
	push rsi
	push rsi
	call p_reduce_fast
	pop rsi
	pop rsi
	cmp eax, -2
	jne 1f
	mov edi, ebx
	call p_reduce_gss
1:	test eax, eax
	js .Lad_noaction
	cmp eax, ebx
	je .Lad_reduced
	mov edi, eax
	mov esi, ebx
	call p_renumber
.Lad_reduced:
	mov rax, qword ptr [r15+C_HEADS]
	mov eax, dword ptr [rax + rbx*8 + H_NODE]
	lea rax, [rax+rax*2]
	mov rdx, qword ptr [r15+C_SN]
	movzx r13d, word ptr [rdx + rax*8 + SN_STATE]
	jmp .Lad_lookup
# The state's only action is a reduce whose path has one link per node, no extras and at least one
# child (p_reduce_fast's quick path, inline): C pops into a new version, pushes the parent, merges
# it into an earlier version or renumbers it to this one. With one version that is the same as
# building the parent in place: the head node is rewritten as the parent's node (its position is
# already the last child's end) and the nodes below it go back to the free list as the chain they
# already form. ebx = version, rsi = the action.
.Lad_inplace:
	mov dword ptr [rsp+12], ebx
	mov r12, rsi
	mov eax, esi
	shr eax, 8
	movzx ebp, al                       # children
	test ebp, ebp
	jz .Lad_rslow
	mov eax, dword ptr [r15+C_NK]
	lea esi, [rax + rbp]
	cmp esi, dword ptr [r15+C_KCAP]
	ja .Lad_rslow0
	mov r8, qword ptr [r15+C_SN]
	mov r9, qword ptr [r15+C_NODES]
	mov r10, qword ptr [r15+C_KIDS]
	mov rax, qword ptr [r15+C_HEADS]
	mov ecx, dword ptr [rax + rbx*8 + H_NODE]
	xor edi, edi                        # children's dynamic precedence
	mov edx, ebp
1:	lea r11, [rcx+rcx*2]
	cmp byte ptr [r8 + r11*8 + SN_NL], 1
	jne .Lad_rslow0
	mov eax, dword ptr [r8 + r11*8 + SN_L0T]
	mov r13d, ecx                       # the lowest popped node
	mov ecx, dword ptr [r8 + r11*8 + SN_L0]
	mov r11, rax
	TREE_OFF r11
	cmp byte ptr [r9 + r11 + N_EXTRA], 0
	jne .Lad_rslow0
	dec esi
	mov dword ptr [r10 + rsi*4], eax
	add edi, dword ptr [r9 + r11 + N_DYN]
	dec edx
	jnz 1b
	lea r11, [rcx+rcx*2]                # ecx = base node
	movzx edx, word ptr [r8 + r11*8 + SN_STATE]
	imul edx, dword ptr [r15+C_LANG+L_NSYM]
	mov rax, r12
	shr rax, 16
	movzx eax, ax
	add edx, eax
	mov rax, qword ptr [r15+C_LANG+L_PARSE_TABLE]
	movzx edx, word ptr [rax + rdx*2]   # next state
	ALLOC_NODE eax                      # parent
	mov r9, qword ptr [r15+C_NODES]
	mov r11, rax
	TREE_OFF r11
	add r11, r9
	mov dword ptr [r11+N_CC], ebp
	mov dword ptr [r11+N_CI], esi
	mov ebx, dword ptr [r10 + rsi*4]
	TREE_OFF rbx
	mov ebx, dword ptr [r9 + rbx + N_START]
	mov dword ptr [r11+N_START], ebx
	add esi, ebp
	mov dword ptr [r15+C_NK], esi
	mov ebx, dword ptr [r10 + rsi*4 - 4]
	TREE_OFF rbx
	mov ebx, dword ptr [r9 + rbx + N_END]
	mov dword ptr [r11+N_END], ebx
	mov rbx, r12
	shr rbx, 16
	movzx ebp, bx                       # symbol
	shr rbx, 16
	movzx ebx, bl
	shl ebx, 16
	or ebx, ebp
	mov dword ptr [r11+N_SYM], ebx
	sar r12, 48
	add edi, r12d                       # the action's dynamic precedence
	mov dword ptr [r11+N_DYN], edi
	lea rbx, [rcx+rcx*2]
	add edi, dword ptr [r8 + rbx*8 + SN_DYN]
	mov ebx, dword ptr [rsp+12]
	cmp dword ptr [r15+C_NH], 1
	jne .Lad_place
	mov rbx, qword ptr [r15+C_HEADS]
	mov ebx, dword ptr [rbx+H_NODE]     # the head node, reused
	lea r12, [rbx+rbx*2]
	lea r12, [r8 + r12*8]
	cmp r13d, ebx
	je 2f
	mov r10d, dword ptr [r12+SN_L0]
	mov r11d, dword ptr [r15+C_SFREE]
	lea rbp, [r13+r13*2]
	mov dword ptr [r8 + rbp*8 + SN_L0], r11d
	mov dword ptr [r15+C_SFREE], r10d
2:	or edx, 0x10000                     # one link, unmarked
	mov dword ptr [r12+SN_STATE], edx
	mov dword ptr [r12+SN_DYN], edi
	mov dword ptr [r12+SN_L0], ecx
	mov dword ptr [r12+SN_L0T], eax
	xor ebx, ebx
	movzx r13d, dx
	jmp .Lad_lookup
.Lad_place:
	mov r12, qword ptr [r15+C_HEADS]
	mov r12d, dword ptr [r12 + rbx*8 + H_NODE]
	lea r12, [r12+r12*2]
	mov r13d, dword ptr [r8 + r12*8 + SN_POS]
	mov r12d, eax
	call .Lrf_place
	test edx, edx
	jnz .Lad_unreduced                  # it merged: this version is left as it was
	mov rcx, qword ptr [r15+C_HEADS]
	mov dword ptr [rcx + rbx*8 + H_NODE], eax
	lea rax, [rax+rax*2]
	mov rcx, qword ptr [r15+C_SN]
	movzx r13d, word ptr [rcx + rax*8 + SN_STATE]
	jmp .Lad_lookup
.Lad_rslow0:                            # r13 is the head's state again for p_reduce_fast's -1
	mov rsi, r12
	HEAD_STATE_R13
	jmp .Lad_rslow
.Lad_unreduced:
	HEAD_STATE_R13
	jmp .Lad_noaction
.Lad_acc_or_rec:
	cmp eax, 2
	jne .Lad_dead
	mov edi, ebx
	call p_accept
	jmp .Lad_ret
.Lad_multi:
	test ecx, ecx
	jz .Lad_noaction
	mov dword ptr [rsp+4], ecx
	mov dword ptr [rsp], 0
	mov dword ptr [rsp+8], -1
.Lad_mloop:
	mov ecx, dword ptr [rsp]
	cmp ecx, dword ptr [rsp+4]
	jae .Lad_mdone
	inc dword ptr [rsp]
	mov rdx, qword ptr [r15+C_LANG+L_ACTIONS]
	lea eax, [rbp + rcx + 1]
	mov rsi, qword ptr [rdx + rax*8]
	mov eax, esi
	and eax, 3
	jz .Lad_mshift
	cmp eax, 1
	jne .Lad_macc
	mov edi, ebx
	xor edx, edx
	push rsi
	push rsi
	call p_reduce_fast
	pop rsi
	pop rsi
	cmp eax, -2
	jne 1f
	mov edi, ebx
	call p_reduce_gss
1:	test eax, eax
	js .Lad_mloop
	mov dword ptr [rsp+8], eax
	jmp .Lad_mloop
.Lad_mshift:
	mov ecx, esi
	shr ecx, 2
	and ecx, 1
	mov eax, esi
	shr eax, 16
	test ecx, ecx
	cmovnz eax, r13d
	mov edi, ebx
	mov esi, eax
	mov edx, r14d
	call p_shift
	jmp .Lad_ret
.Lad_macc:
	cmp eax, 2
	jne .Lad_dead
	mov edi, ebx
	call p_accept
	jmp .Lad_ret
.Lad_mdone:
	mov edi, dword ptr [rsp+8]
	test edi, edi
	js .Lad_noaction
	mov esi, ebx
	call p_renumber
	jmp .Lad_reduced
.Lad_noaction:
	# keyword -> word token fallback
	cmp dword ptr [r15+C_TKW], 0
	je .Lad_dead
	cmp r14d, dword ptr [r15+C_LANG+L_WORD]
	je .Lad_dead
	mov rdx, qword ptr [r15+C_LANG+L_RESERVED_SET]
	movzx eax, byte ptr [rdx + r13]
	imul eax, dword ptr [r15+C_LANG+L_RWORDS]
	mov edx, r14d
	shr edx, 6
	add eax, edx
	mov rdx, qword ptr [r15+C_LANG+L_RESERVED_BITS]
	mov rax, qword ptr [rdx + rax*8]
	bt rax, r14
	jc .Lad_dead
	mov eax, r13d
	imul eax, dword ptr [r15+C_LANG+L_NSYM]
	add eax, dword ptr [r15+C_LANG+L_WORD]
	mov rdx, qword ptr [r15+C_LANG+L_PARSE_TABLE]
	movzx eax, word ptr [rdx + rax*2]
	mov rdx, qword ptr [r15+C_LANG+L_ACTIONS]
	cmp byte ptr [rdx + rax*8], 0
	je .Lad_dead
	mov r14d, dword ptr [r15+C_LANG+L_WORD]
	mov ebp, eax
	jmp .Lad_entry
.Lad_dead:
	mov rax, qword ptr [r15+C_HEADS]
	mov dword ptr [rax + rbx*8 + H_DEAD], 1
.Lad_ret:
.endm

# ---------------------------------------------------------------------------
# p_emit() -> rax = node count, nodes in the context's output buffer
# ---------------------------------------------------------------------------
p_emit:
	push rbx
	push rbp
	push r12
	push r13
	push r14
	mov esi, 1                          # the root; the rest grows as nodes are emitted
	cmp esi, dword ptr [r15+C_OUTCAP]
	jbe 1f
	lea rdi, [r15+C_OUT]
	mov ecx, 16
	call p_grow
1:	mov r8, qword ptr [r15+C_NODES]
	mov r12, qword ptr [r15+C_OUT]
	mov ecx, dword ptr [r15+C_FINISHED]
	mov eax, ecx
	TREE_OFF rax
	lea r9, [r8 + rax]
	mov r13, qword ptr [r15+C_LANG+L_SYMBOL_OUT]
	movzx eax, word ptr [r9+N_SYM]
	mov eax, dword ptr [r13 + rax*4]
	btr eax, 31
	mov dword ptr [r12], eax
	mov rax, qword ptr [r9+N_START]
	mov qword ptr [r12+4], rax
	mov dword ptr [r12+12], -1
	mov r14d, 1                         # n
	# frame stack
	cmp dword ptr [r15+C_ESTKCAP], 0
	jne 2f
	mov esi, 1
	call p_grow_estk
2:	mov rbx, qword ptr [r15+C_ESTK]
	xor ebp, ebp                        # sp (frames)
	mov dword ptr [rbx], ecx
	mov qword ptr [rbx+4], 0
	mov dword ptr [rbx+12], 0
	inc ebp
	mov r10, qword ptr [r15+C_KIDS]
	mov r8, qword ptr [r15+C_NODES]
.Lem_loop:
	test ebp, ebp
	jz .Lem_done
	mov eax, ebp
	shl eax, 4
	lea rdi, [rbx + rax - 16]           # frame ptr
	mov eax, dword ptr [rdi]
	TREE_OFF rax
	lea r9, [r8 + rax]                  # parent node
	mov ecx, dword ptr [rdi+4]          # ci
	cmp ecx, dword ptr [r9+N_CC]
	jae .Lem_pop
	lea edx, [rcx+1]
	mov dword ptr [rdi+4], edx
	add ecx, dword ptr [r9+N_CI]
	mov esi, dword ptr [r10 + rcx*4]    # child index
	cmp edx, dword ptr [r9+N_CC]        # start loading the next sibling
	jae 1f
	mov eax, dword ptr [r10 + rcx*4 + 4]
	TREE_OFF rax
	prefetcht0 [r8 + rax]
1:
	mov eax, esi
	TREE_OFF rax
	lea r11, [r8 + rax]                 # child node
	xor edx, edx                        # alias
	cmp byte ptr [r11+N_EXTRA], 0
	jne 2f
	movzx eax, byte ptr [r9+N_PROD]
	shl eax, 4
	add eax, dword ptr [rdi+8]
	inc dword ptr [rdi+8]
	mov rcx, qword ptr [r15+C_LANG+L_ALIAS_SEQ]
	movzx edx, word ptr [rcx + rax*2]
2:	movzx eax, word ptr [r11+N_SYM]
	test edx, edx
	cmovnz eax, edx                     # s
	mov eax, dword ptr [r13 + rax*4]    # output word, visible in bit 31
	mov r9d, dword ptr [rdi+12]         # parent out index
	btr eax, 31
	jc 3f
	test edx, edx                       # an aliased node is visible
	jz 4f
3:	cmp r14d, dword ptr [r15+C_OUTCAP]
	jae .Lem_grow
.Lem_put:
	mov rdx, r14
	shl rdx, 4
	add rdx, r12
	mov dword ptr [rdx], eax
	mov rax, qword ptr [r11+N_START]
	mov qword ptr [rdx+4], rax
	mov dword ptr [rdx+12], r9d
	mov r9d, r14d
	inc r14
4:	cmp dword ptr [r11+N_CC], 0
	je .Lem_loop
	# push frame (child, 0, 0, parent)
	lea eax, [rbp+1]
	cmp eax, dword ptr [r15+C_ESTKCAP]
	jb 5f
	push rsi
	mov esi, eax
	call p_grow_estk
	pop rsi
	mov rbx, qword ptr [r15+C_ESTK]
5:	mov eax, ebp
	shl eax, 4
	mov dword ptr [rbx + rax], esi
	mov qword ptr [rbx + rax + 4], 0
	mov dword ptr [rbx + rax + 12], r9d
	inc ebp
	jmp .Lem_loop
.Lem_pop:
	dec ebp
	jmp .Lem_loop
.Lem_done:
	mov rax, r14
	jmp .Lem_ret
.Lem_grow:
	push rdi
	push rsi
	lea rdi, [r15+C_OUT]
	lea esi, [r14+1]
	mov ecx, 16
	call p_grow
	pop rsi
	pop rdi
	mov r12, qword ptr [r15+C_OUT]
	jmp .Lem_put
.Lem_ret:
	pop r14
	pop r13
	pop r12
	pop rbp
	pop rbx
	ret

# ---------------------------------------------------------------------------
# int64_t tsasm_parse(TsasmParser *p, const TsasmLanguage *lang, const uint8_t *src, uint64_t len,
#                     const TsasmNode **nodes)
# ---------------------------------------------------------------------------
	.globl tsasm_parse
	.type tsasm_parse, @function
	.p2align 4
tsasm_parse:
	push rbx
	push rbp
	push r12
	push r13
	push r14
	push r15
	sub rsp, 24                         # ADVANCE's locals
	mov r15, rdi
	mov qword ptr [r15+C_SAVEDRSP], rsp
	mov qword ptr [r15+C_RESULT], r8
	.irp off, 0, 16, 32, 48, 64, 80, 96, 112
	movdqu xmm0, xmmword ptr [rsi + \off]
	movdqu xmmword ptr [r15 + C_LANG + \off], xmm0
	.endr
	mov rsi, rdx
	mov rdx, rcx
	mov rax, qword ptr [r15+C_RETAIN]   # drop the last parse's big output array
	cmp qword ptr [r15+C_MEMUSED], rax
	jbe 1f
	push rsi
	push rdx
	call p_release
	pop rdx
	pop rsi
1:	mov rdi, rsi
	mov rsi, rdx
	mov rax, rsi
	shl rax, 6
	add rax, 10000
	mov qword ptr [r15+C_STEPS], rax    # work budget: 64 * len + 10000
	mov rax, rsi
	shl rax, 5
	add rax, 100000
	mov r8d, 0x7FFFFFF
	cmp rax, r8
	cmova rax, r8
	mov dword ptr [r15+C_NODELIM], eax  # node budget: 32 * len + 100000
	call p_set_navail
	mov rax, ERR_LIMIT
	mov r8d, 0xFFFFFFF0                 # byte offsets are 32-bit: reject inputs >= ~4 GiB
	cmp rsi, r8
	jae .Lmain_ret
	mov qword ptr [r15+C_SRC], rdi
	add rsi, rdi
	mov qword ptr [r15+C_END], rsi
	xor eax, eax
	mov dword ptr [r15+C_NN], eax
	mov dword ptr [r15+C_NK], eax
	mov dword ptr [r15+C_TOKVALID], eax
	mov dword ptr [r15+C_LASTPOS], eax
	mov dword ptr [r15+C_SFREE], eax
	mov dword ptr [r15+C_XFREE], eax
	mov dword ptr [r15+C_FINISHED], -1
	mov dword ptr [r15+C_SNN], 1
	mov dword ptr [r15+C_XN], 1
	# tree 0: the zeroed tree under the base stack node
	ALLOC_NODE eax
	mov r8, qword ptr [r15+C_NODES]
	pxor xmm0, xmm0
	movdqu xmmword ptr [r8], xmm0
	movq qword ptr [r8+16], xmm0
	# stack node 0: the base (state 1, position 0, no links); one active version on it
	cmp dword ptr [r15+C_SNCAP], 0
	jne 2f
	lea rdi, [r15+C_SN]
	mov esi, 1
	mov ecx, SN_SIZE
	call p_grow
2:	mov r8, qword ptr [r15+C_SN]
	mov qword ptr [r8], 1               # state 1, no links, unmarked, precedence 0
	mov qword ptr [r8+8], 0
	mov qword ptr [r8+16], 0
	cmp dword ptr [r15+C_HCAP], 0
	jne 3f
	lea rdi, [r15+C_HEADS]
	mov esi, 8
	mov ecx, 8
	call p_grow
3:	mov rax, qword ptr [r15+C_HEADS]
	mov qword ptr [rax], 0
	mov dword ptr [r15+C_NH], 1

.Lmain_outer:                           # the version loop of ts_parser_parse
	cmp dword ptr [r15+C_NH], 0
	je .Lmain_end
	xor ebx, ebx                        # version
.Lmain_vloop:
	cmp ebx, dword ptr [r15+C_NH]
	jae .Lmain_condense
.Lmain_adv:
	mov rax, qword ptr [r15+C_HEADS]
	cmp dword ptr [rax + rbx*8 + H_DEAD], 0
	jne .Lmain_vnext
	ADVANCE
	mov rax, qword ptr [r15+C_HEADS]
	cmp dword ptr [rax + rbx*8 + H_DEAD], 0
	jne .Lmain_vnext
	mov eax, dword ptr [rax + rbx*8 + H_NODE]
	lea rax, [rax+rax*2]
	mov rdx, qword ptr [r15+C_SN]
	mov eax, dword ptr [rdx + rax*8 + SN_POS]
	mov ecx, dword ptr [r15+C_LASTPOS]
	cmp eax, ecx
	ja .Lmain_newpos
	jb .Lmain_adv
	test ebx, ebx
	jz .Lmain_adv
.Lmain_newpos:
	mov dword ptr [r15+C_LASTPOS], eax
	cmp dword ptr [r15+C_NH], 1         # one version: condensing would change nothing
	je .Lmain_adv
.Lmain_vnext:
	inc ebx
	jmp .Lmain_vloop

.Lmain_condense:                        # ts_parser__condense_stack without error costs
	xor ebx, ebx                        # i
.Lcd_i:
	cmp ebx, dword ptr [r15+C_NH]
	jae .Lcd_cap
	sub qword ptr [r15+C_STEPS], 1
	jb p_limit
	mov rax, qword ptr [r15+C_HEADS]
	cmp dword ptr [rax + rbx*8 + H_DEAD], 0
	je 1f
	mov edi, ebx
	call p_remove_version
	jmp .Lcd_i
1:	xor ebp, ebp                        # j
.Lcd_j:
	cmp ebp, ebx
	jae .Lcd_inext
	mov rax, qword ptr [r15+C_HEADS]
	mov rdx, qword ptr [r15+C_SN]
	mov ecx, dword ptr [rax + rbp*8 + H_NODE]
	lea rcx, [rcx+rcx*2]
	lea rcx, [rdx + rcx*8]
	mov esi, dword ptr [rax + rbx*8 + H_NODE]
	lea rsi, [rsi+rsi*2]
	lea rsi, [rdx + rsi*8]
	mov edi, dword ptr [rcx+SN_POS]     # p_merge's own test, inline: most pairs differ
	cmp edi, dword ptr [rsi+SN_POS]
	jne 2f
	mov di, word ptr [rcx+SN_STATE]
	cmp di, word ptr [rsi+SN_STATE]
	jne 2f
	mov edi, ebp
	mov esi, ebx
	call p_merge                        # both heads are live, so it merges
	jmp .Lcd_i                          # i now holds the next version
2:	mov ecx, dword ptr [rcx+SN_DYN]     # the higher dynamic precedence moves first
	cmp ecx, dword ptr [rsi+SN_DYN]
	jge .Lcd_jnext
	mov rcx, qword ptr [rax + rbx*8]
	mov rdx, qword ptr [rax + rbp*8]
	mov qword ptr [rax + rbx*8], rdx
	mov qword ptr [rax + rbp*8], rcx
.Lcd_jnext:
	inc ebp
	jmp .Lcd_j
.Lcd_inext:
	inc ebx
	jmp .Lcd_i
.Lcd_cap:
	cmp dword ptr [r15+C_NH], MAXVERSIONS
	jbe .Lmain_outer
	mov edi, MAXVERSIONS
	call p_remove_version
	jmp .Lcd_cap

.Lmain_end:
	cmp dword ptr [r15+C_FINISHED], 0
	jge 1f
	mov rax, ERR_SYNTAX
	jmp .Lmain_ret
1:	call p_emit
.Lmain_ret:
	mov rcx, qword ptr [r15+C_RETAIN]   # a big parse gives its buffers back now,
	cmp qword ptr [r15+C_MEMUSED], rcx  # keeping only the nodes it returns
	jbe 3f
	push rax
	push rax
	test rax, rax
	js 4f
	call p_release_work
	jmp 5f
4:	call p_release
5:	pop rax
	pop rax
3:
	mov rcx, qword ptr [r15+C_RESULT]
	test rcx, rcx
	jz 2f
	xor edx, edx
	test rax, rax
	cmovns rdx, qword ptr [r15+C_OUT]
	mov qword ptr [rcx], rdx
2:	add rsp, 24
	pop r15
	pop r14
	pop r13
	pop r12
	pop rbp
	pop rbx
	ret
	.size tsasm_parse, .-tsasm_parse

	.set C_ALLOC, (C_SIZE + 63) & ~63

# TsasmParser *tsasm_parser_new(void): zeroed, cache-line aligned context (NULL if out of memory)
	.globl tsasm_parser_new
	.type tsasm_parser_new, @function
tsasm_parser_new:
	push rbx
	mov edi, 64
	mov esi, C_ALLOC
	call aligned_alloc@PLT
	test rax, rax
