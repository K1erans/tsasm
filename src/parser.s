# tsasm: tree-sitter style GLR parser runtime, x86-64 (GNU as, intel syntax), any grammar without an external scanner
#
# Exports (System V AMD64):
#   TsasmParser *tsasm_parser_new(void), void tsasm_parser_free(TsasmParser *),
#   void tsasm_parser_set_memory_limit(TsasmParser *, uint64_t)
#   int64_t tsasm_parse(TsasmParser *p, const TsasmLanguage *lang, const uint8_t *src, uint64_t len,
#                       const TsasmNode **nodes)
#   const char *tsasm_language_symbol_name(const TsasmLanguage *, uint16_t),
#   uint32_t tsasm_language_symbol_count(const TsasmLanguage *)
# Grammar tables and lexers live in per-grammar objects generated by gen/gen.py.
#
# Internal convention: r15 = the caller's TsasmParser for the whole parse (callee-saved, never
# modified inside). There is no writable static data: a call touches only its own context.
# Internal functions follow SysV (rbx, rbp, r12-r15 preserved). Grow helpers preserve ALL
# registers except flags, so hot paths can call them without spilling.
#
# Data model:
#   Node  (32 bytes): u16 symbol, u8 production_id, u8 extra, u32 start, u32 end,
#                     u32 child_count, u32 child_index (into kids[]), i32 dynamic_precedence
#   Entry (8 bytes) : u32 node, u32 state | (extra << 16)
#   Version (32 bytes): ptr entries, u32 size, u32 cap, u32 status (0 active,1 dead,2 accepted), i32 dynsum

	.intel_syntax noprefix

	.set C_NODES, 0
	.set C_NN, 8
	.set C_NCAP, 12
	.set C_KIDS, 16
	.set C_NK, 24
	.set C_KCAP, 28
	.set C_SRC, 32
	.set C_END, 40
	.set C_NV, 48
	.set C_FINISHED, 52
	.set C_LASTPOS, 56
	.set C_TOKVALID, 60
	.set C_TSYM, 64
	.set C_TSTART, 68
	.set C_TEND, 72
	.set C_TPOS, 76
	.set C_TKW, 80
	.set C_TPSTATE, 84
	.set C_OUT, 88
	.set C_OUTCAP, 100
	.set C_ESTK, 104
	.set C_ESTKCAP, 116
	.set C_SAVEDRSP, 120
	.set C_STEPS, 128
	.set C_NODELIM, 136
	.set C_MEMUSED, 144
	.set C_MEMLIMIT, 152
	.set C_CAPHIT, 160
	.set C_RESULT, 168
	.set C_NEXTGID, 176                 # merge group ids handed out this parse
	.set C_GLIVE, 180                   # bit0: a group formed this condense, bit1: some V_GID != 0
	.set C_NAVAIL, 184                  # min(node capacity, node budget): ALLOC_NODE's bound
	.set C_LANG, 192                   # copy of the TsasmLanguage descriptor for this parse
	.set C_VERS, 320
	.set MAXVERS, 128
	.set MAXV, 64
	.set C_SIZE, C_VERS + MAXVERS * 32

# TsasmLanguage descriptor, emitted per grammar by gen/gen.py
	.set L_PARSE_TABLE, 0               # u16 [states][nsym] -> action index or goto state
	.set L_ACTIONS, 8                   # u64 action words, header word first
	.set L_LEX_STATE, 16                # u16 [states] lex mode
	.set L_RESERVED_SET, 24             # u8 [states] reserved word set id
	.set L_RESERVED_BITS, 32            # u64 [sets][rwords] token bitsets
	.set L_SYMBOL_FLAGS, 40             # u8 [total syms] bit0 visible, bit1 named
	.set L_PUBLIC_SYMBOL, 48            # u16 [total syms]
	.set L_ALIAS_SEQ, 56                # u16 [productions][16]
	.set L_SYMBOL_NAMES, 64             # char * [total syms]
	.set L_LEX_MAIN, 72                 # lexer entry (register contract in gen.py)
	.set L_LEX_KEYWORD, 80              # keyword lexer entry, 0 if none
	.set L_NSYM, 88                     # u32 symbol count (parse table row length)
	.set L_TOTAL_SYMS, 92               # u32 symbols + aliases
	.set L_WORD, 96                     # u32 keyword capture token, 0 if none
	.set L_RWORDS, 100                  # u32 qwords per reserved word set
	.set L_SYMBOL_OUT, 112              # u32 [total syms] public symbol | named << 16 | visible << 31
	.set L_SIZE, 128

	.set ERR_SYNTAX, -1
	.set ERR_LIMIT, -3
	.set ERR_NOMEM, -4
	.set DEFAULT_MEMLIMIT, 1 << 30
	.set RETAIN_LIMIT_SHIFT, 3          # an eighth of the memory limit
	.set RETAIN_SHIFT, 8                # 256 bytes of buffers per input byte

	.set V_E, 0
	.set V_SIZE, 8
	.set V_CAP, 12
	.set V_STATUS, 16
	.set V_DYN, 20
	.set V_GID, 24                      # merge group: versions C tree-sitter held as one stack head this step
	.set V_NGID, 28                     # the group being formed by the current condense

	.set N_SYM, 0
	.set N_PROD, 2
	.set N_EXTRA, 3
	.set N_START, 4
	.set N_END, 8
	.set N_CC, 12
	.set N_CI, 16
	.set N_DYN, 20

	.text

# ---------------------------------------------------------------------------
# grow helpers: preserve every GPR (except rax where documented), realign stack for libc
# ---------------------------------------------------------------------------
.macro SAVE_VOLATILE
	push rbp
	mov rbp, rsp
	push rax
	push rcx
	push rdx
	push rsi
	push rdi
	push r8
	push r9
	push r10
	push r11
	and rsp, -16
.endm
.macro RESTORE_VOLATILE
	lea rsp, [rbp-72]
	pop r11
	pop r10
	pop r9
	pop r8
	pop rdi
	pop rsi
	pop rdx
	pop rcx
	pop rax
	pop rbp
.endm

# Growable buffers share one layout: qword pointer at +0, dword capacity (entries) at +12.
#
# p_grow(rdi = buffer, esi = entries needed, ecx = log2 entry size): grow to at least esi
# entries (doubling, at least 256). The size increase is charged to C_MEMUSED against
# C_MEMLIMIT before realloc, and pointer, capacity and usage are stored only after realloc
# succeeds, so an aborted parse leaves a consistent context. Preserves every GPR.
p_grow:
	SAVE_VOLATILE
	mov r8, rdi
	mov r9d, dword ptr [r8+12]
	mov edx, 256
	cmp edx, r9d
	cmovb edx, r9d
1:	cmp edx, esi
	jae 2f
	add edx, edx
	jc p_limit
	jmp 1b
2:	mov eax, edx
	sub eax, r9d
	shl rax, cl
	add rax, qword ptr [r15+C_MEMUSED]
	cmp rax, qword ptr [r15+C_MEMLIMIT]
	ja p_limit
	push rdx
	push rax
	push r8
	push r8
	mov esi, edx
	shl rsi, cl
	mov rdi, qword ptr [r8]
	call realloc@PLT
	pop r8
	pop r8
	pop rcx
	pop rdx
	test rax, rax
	jz p_oom
	mov qword ptr [r8], rax
	mov dword ptr [r8+12], edx
	mov qword ptr [r15+C_MEMUSED], rcx
	RESTORE_VOLATILE
	ret

# p_grow_nodes: make nn < navail, growing the arena if needed; the node budget C_NODELIM is
# enforced here, so a capacity kept from an earlier parse cannot lift it. Preserves every GPR.
p_grow_nodes:
	push rdi
	push rsi
	push rcx
	mov esi, dword ptr [r15+C_NN]
	cmp esi, dword ptr [r15+C_NODELIM]
	jae p_limit
	cmp esi, dword ptr [r15+C_NCAP]
	jb 1f
	inc esi
	lea rdi, [r15+C_NODES]
	mov ecx, 5
	call p_grow
1:	call p_set_navail
	pop rcx
	pop rsi
	pop rdi
	ret

# p_set_navail: C_NAVAIL = min(C_NCAP, C_NODELIM). Preserves every GPR but rcx.
p_set_navail:
	mov ecx, dword ptr [r15+C_NCAP]
	cmp ecx, dword ptr [r15+C_NODELIM]
	cmova ecx, dword ptr [r15+C_NODELIM]
	mov dword ptr [r15+C_NAVAIL], ecx
	ret

# p_grow_kids(edi = count): make nk + edi <= kcap. Preserves every GPR.
p_grow_kids:
	push rdi
	push rsi
	push rcx
	mov esi, dword ptr [r15+C_NK]
	add esi, edi
	jc p_limit
	lea rdi, [r15+C_KIDS]
	mov ecx, 2
	call p_grow
	pop rcx
	pop rsi
	pop rdi
	ret

# p_grow_vstack(rdi = version, esi = entries). Preserves every GPR.
p_grow_vstack:
	push rcx
	mov ecx, 3
	call p_grow
	pop rcx
	ret

# p_grow_estk(esi = frames): 16-byte frames used by emit and subtree compare. Preserves every GPR.
p_grow_estk:
	push rdi
	push rcx
	lea rdi, [r15+C_ESTK]
	mov ecx, 4
	call p_grow
	pop rcx
	pop rdi
	ret

# Budget aborts unwind straight to the end of tsasm_parse_go.
p_limit:
	mov eax, ERR_LIMIT
	jmp 1f
p_oom:
	mov eax, ERR_NOMEM
1:	mov rsp, qword ptr [r15+C_SAVEDRSP]
	movsxd rax, eax
	jmp .Lmain_ret

# p_release: free every buffer the context owns and zero their capacities (r15 = ctx).
p_release:
	push rbx
	push r12
	push r13
	lea rbx, [r15 + C_VERS]
	lea r12, [r15 + C_SIZE]
1:	mov rdi, qword ptr [rbx+V_E]
	call free@PLT
	mov qword ptr [rbx+V_E], 0
	mov qword ptr [rbx+V_SIZE], 0
	add rbx, 32
	cmp rbx, r12
	jb 1b
	mov rdi, qword ptr [r15+C_NODES]
	call free@PLT
	mov rdi, qword ptr [r15+C_KIDS]
	call free@PLT
	mov rdi, qword ptr [r15+C_ESTK]
	call free@PLT
	mov rdi, qword ptr [r15+C_OUT]
	call free@PLT
	mov qword ptr [r15+C_OUT], 0
	mov dword ptr [r15+C_OUTCAP], 0
	mov qword ptr [r15+C_NODES], 0
	mov qword ptr [r15+C_KIDS], 0
	mov qword ptr [r15+C_ESTK], 0
	mov dword ptr [r15+C_NCAP], 0
	mov dword ptr [r15+C_KCAP], 0
	mov dword ptr [r15+C_ESTKCAP], 0
	mov qword ptr [r15+C_MEMUSED], 0
	pop r13
	pop r12
	pop rbx
	ret

# ALLOC_NODE reg32: reg = new node index (nn++), may grow (preserves regs)
.macro ALLOC_NODE reg
	mov \reg, dword ptr [r15+C_NN]
	cmp \reg, dword ptr [r15+C_NAVAIL]
	jb 91f
	call p_grow_nodes
91:	inc dword ptr [r15+C_NN]
.endm

# ---------------------------------------------------------------------------
# p_lex(edi = parse state, esi = byte position) -> eax = 1 token lexed into cache, 0 = no token
# ---------------------------------------------------------------------------
	.p2align 4
p_lex:
	push rbx
	push r12
	push r13
	mov ebx, edi
	mov dword ptr [r15+C_TPOS], esi
	mov dword ptr [r15+C_TPSTATE], edi
	mov rsi, qword ptr [r15+C_SRC]
	mov r12, rsi                        # r12 = src base
	mov eax, dword ptr [r15+C_TPOS]
	add rsi, rax
	mov r9, qword ptr [r15+C_END]
	mov rax, qword ptr [r15+C_LANG+L_LEX_STATE]
	movzx ecx, word ptr [rax + rbx*2]
	call qword ptr [r15+C_LANG+L_LEX_MAIN]
	cmp ecx, -1
	je .Llex_fail
	sub r10, r12
	sub r11, r12
	cmp r11, r10                        # a token accepted before skipped whitespace starts where
	jae 1f                              # it ends, as in ts_lexer_finish
	mov r10, r11
1:	mov dword ptr [r15+C_TSTART], r10d
	mov dword ptr [r15+C_TEND], r11d
	mov dword ptr [r15+C_TKW], 0
	cmp ecx, dword ptr [r15+C_LANG+L_WORD]
	jne .Llex_store
	cmp qword ptr [r15+C_LANG+L_LEX_KEYWORD], 0
	je .Llex_store
	# keyword extraction
	mov r13d, r11d                      # identifier end offset
	lea rsi, [r12 + r10]
	call qword ptr [r15+C_LANG+L_LEX_KEYWORD]
	cmp ecx, -1
	je .Llex_word
	mov dword ptr [r15+C_TKW], 1
	sub r11, r12
	cmp r11d, r13d
	jne .Llex_word
	# has_actions(state, kw) || is_reserved(state, kw)
	mov eax, ebx
	imul eax, dword ptr [r15+C_LANG+L_NSYM]
	add eax, ecx
	mov rdx, qword ptr [r15+C_LANG+L_PARSE_TABLE]
	movzx eax, word ptr [rdx + rax*2]
	test eax, eax
	jnz .Llex_store
	mov rdx, qword ptr [r15+C_LANG+L_RESERVED_SET]
	movzx eax, byte ptr [rdx + rbx]
	imul eax, dword ptr [r15+C_LANG+L_RWORDS]
	mov edx, ecx
	shr edx, 6
	add eax, edx
	mov rdx, qword ptr [r15+C_LANG+L_RESERVED_BITS]
	mov rax, qword ptr [rdx + rax*8]
	bt rax, rcx
	jc .Llex_store
.Llex_word:
	mov ecx, dword ptr [r15+C_LANG+L_WORD]
.Llex_store:
	mov dword ptr [r15+C_TSYM], ecx
	mov dword ptr [r15+C_TOKVALID], 1
	mov eax, 1
	pop r13
	pop r12
	pop rbx
	ret
.Llex_fail:
	mov dword ptr [r15+C_TOKVALID], 0
	xor eax, eax
	pop r13
	pop r12
	pop rbx
	ret

# ---------------------------------------------------------------------------
# p_can_reuse(edi = state) -> eax (cached token reusable in this state)
# ---------------------------------------------------------------------------
	.p2align 4
p_can_reuse:
	mov ecx, dword ptr [r15+C_TSYM]
	mov eax, edi
	imul eax, dword ptr [r15+C_LANG+L_NSYM]
	add eax, ecx
	mov rdx, qword ptr [r15+C_LANG+L_PARSE_TABLE]
	movzx eax, word ptr [rdx + rax*2]
	mov rdx, qword ptr [r15+C_LANG+L_ACTIONS]
	mov r8, qword ptr [rdx + rax*8]     # header
	test r8b, r8b
	jz .Lcr_size
	mov esi, dword ptr [r15+C_TPSTATE]
	mov rdx, qword ptr [r15+C_LANG+L_LEX_STATE]
	movzx eax, word ptr [rdx + rsi*2]
	movzx r9d, word ptr [rdx + rdi*2]
	cmp eax, r9d
	jne .Lcr_size
	mov rdx, qword ptr [r15+C_LANG+L_RESERVED_SET]
	movzx eax, byte ptr [rdx + rsi]
	movzx r9d, byte ptr [rdx + rdi]
	cmp eax, r9d
	jne .Lcr_size
	cmp ecx, dword ptr [r15+C_LANG+L_WORD]
	jne .Lcr_yes
	cmp dword ptr [r15+C_TKW], 0
	jne .Lcr_size
	cmp esi, edi
	je .Lcr_yes
.Lcr_size:
	mov eax, dword ptr [r15+C_TEND]
	cmp eax, dword ptr [r15+C_TSTART]
	jne .Lcr_flag
	test ecx, ecx
	jz .Lcr_flag
	xor eax, eax
	ret
.Lcr_flag:
	mov rax, r8
	shr eax, 8
	and eax, 1
	ret
.Lcr_yes:
	mov eax, 1
	ret

# ---------------------------------------------------------------------------
# p_shift(rdi = version ptr, esi = state, edx = symbol, ecx = extra flag)
# leaf start/end come from the token cache
# ---------------------------------------------------------------------------
	.p2align 4
p_shift:
	test edx, edx
	jnz 1f
	mov ecx, 1                          # eof is always extra
1:	ALLOC_NODE eax
	mov r8, qword ptr [r15+C_NODES]
	mov r9d, eax
	shl r9, 5
	add r9, r8                          # node ptr
	mov r10d, ecx
	shl r10d, 24
	or r10d, edx                        # symbol | extra<<24 (prod = 0)
	mov dword ptr [r9+N_SYM], r10d
	mov r10, qword ptr [r15+C_TSTART]   # start, end
	mov qword ptr [r9+N_START], r10
	mov qword ptr [r9+N_CC], 0
	mov dword ptr [r9+N_DYN], 0
	# push entry
	shl ecx, 16
	or esi, ecx
	mov ecx, dword ptr [rdi+V_SIZE]
	cmp ecx, dword ptr [rdi+V_CAP]
	jb 2f
	push rsi
	lea esi, [rcx+1]
	call p_grow_vstack
	pop rsi
2:	mov r8, qword ptr [rdi+V_E]
	mov dword ptr [r8 + rcx*8], eax
	mov dword ptr [r8 + rcx*8 + 4], esi
	inc ecx
	mov dword ptr [rdi+V_SIZE], ecx
	ret

# ---------------------------------------------------------------------------
# p_reduce(rdi = version ptr, rsi = reduce action word)
# ---------------------------------------------------------------------------
	.p2align 4
p_reduce:
	push rbx
	push rbp
	push r12
	push r13
	push r14
	mov r12, rdi
	mov r13, rsi
	mov rbx, qword ptr [r12+V_E]
	mov r14d, dword ptr [r12+V_SIZE]    # i
	mov rax, r13
	shr eax, 8
	movzx ecx, al                       # child count
	test ecx, ecx
	jz .Lrd_popped
.Lrd_pop:
	dec r14d
	test byte ptr [rbx + r14*8 + 6], 1
	jnz .Lrd_pop
	dec ecx
	jnz .Lrd_pop
.Lrd_popped:
	mov ebp, dword ptr [r12+V_SIZE]     # j
.Lrd_trail:
	cmp ebp, r14d
	jbe .Lrd_trdone
	test byte ptr [rbx + rbp*8 - 2], 1
	jz .Lrd_trdone
	dec ebp
	jmp .Lrd_trail
.Lrd_trdone:
	# ensure kids capacity
	mov edi, ebp
	sub edi, r14d
	mov eax, dword ptr [r15+C_NK]
	add eax, edi
	cmp eax, dword ptr [r15+C_KCAP]
	jbe 1f
	call p_grow_kids
1:	ALLOC_NODE eax
	mov r8, qword ptr [r15+C_NODES]
	mov r9d, eax                        # keep n in eax
	shl r9, 5
	add r9, r8                          # node ptr
	mov rcx, r13
	shr rcx, 16
	movzx edx, cx                       # symbol
	shr rcx, 16
	movzx ecx, cl                       # production id
	shl ecx, 16
	or ecx, edx
	mov dword ptr [r9+N_SYM], ecx       # symbol | prod<<16 | extra=0
	mov ecx, ebp
	sub ecx, r14d
	mov dword ptr [r9+N_CC], ecx
	mov r10, qword ptr [r15+C_KIDS]
	mov r11d, dword ptr [r15+C_NK]
	mov dword ptr [r9+N_CI], r11d
	mov rdi, r13
	sar rdi, 48                         # action dynamic precedence
	mov edx, r14d
	cmp edx, ebp
	jae .Lrd_nokids
.Lrd_kids:
	mov esi, dword ptr [rbx + rdx*8]
	mov dword ptr [r10 + r11*4], esi
	inc r11d
	shl rsi, 5
	add edi, dword ptr [r8 + rsi + N_DYN]
	inc edx
	cmp edx, ebp
	jb .Lrd_kids
	mov dword ptr [r15+C_NK], r11d
	mov dword ptr [r9+N_DYN], edi
	mov esi, dword ptr [rbx + r14*8]
	shl rsi, 5
	mov ecx, dword ptr [r8 + rsi + N_START]
	mov dword ptr [r9+N_START], ecx
	mov esi, dword ptr [rbx + rbp*8 - 8]
	shl rsi, 5
	mov ecx, dword ptr [r8 + rsi + N_END]
	mov dword ptr [r9+N_END], ecx
	jmp .Lrd_goto
.Lrd_nokids:
	mov dword ptr [r9+N_DYN], edi
	xor ecx, ecx
	cmp r14d, 1
	jbe 2f
	mov esi, dword ptr [rbx + r14*8 - 8]
	shl rsi, 5
	mov ecx, dword ptr [r8 + rsi + N_END]
2:	mov dword ptr [r9+N_START], ecx
	mov dword ptr [r9+N_END], ecx
.Lrd_goto:
	# version dynsum += action dyn
	mov rdi, r13
	sar rdi, 48
	add dword ptr [r12+V_DYN], edi
	# next = goto(state below, symbol)
	movzx ecx, word ptr [rbx + r14*8 - 4]
	imul ecx, dword ptr [r15+C_LANG+L_NSYM]
	mov rdx, r13
	shr rdx, 16
	movzx edx, dx
	add ecx, edx
	mov rdx, qword ptr [r15+C_LANG+L_PARSE_TABLE]
	movzx ecx, word ptr [rdx + rcx*2]   # next state
	mov edx, dword ptr [r12+V_SIZE]
	sub edx, ebp                        # ntrail
	jnz .Lrd_withtrail
	mov dword ptr [rbx + r14*8], eax
	mov dword ptr [rbx + r14*8 + 4], ecx
	inc r14d
	mov dword ptr [r12+V_SIZE], r14d
	pop r14
	pop r13
	pop r12
	pop rbp
	pop rbx
	ret
.Lrd_withtrail:
	# make room if i == j
	mov esi, dword ptr [r12+V_SIZE]
	inc esi
	cmp esi, dword ptr [r12+V_CAP]
	jbe 3f
	mov rdi, r12
	call p_grow_vstack
	mov rbx, qword ptr [r12+V_E]
3:	mov r8d, ecx
	or r8d, 0x10000                     # extra entries' state
	lea esi, [r14+1]
	cmp esi, ebp
	ja .Lrd_back
	# forward copy e[i+1+k] = e[j+k]
	xor edi, edi
4:	lea r9d, [rbp + rdi]
	mov r10d, dword ptr [rbx + r9*8]
	lea r9d, [rsi + rdi]
	mov dword ptr [rbx + r9*8], r10d
	mov dword ptr [rbx + r9*8 + 4], r8d
	inc edi
	cmp edi, edx
	jb 4b
	jmp .Lrd_tdone
.Lrd_back:
	mov edi, edx
5:	dec edi
	lea r9d, [rbp + rdi]
	mov r10d, dword ptr [rbx + r9*8]
	lea r9d, [rsi + rdi]
	mov dword ptr [rbx + r9*8], r10d
	mov dword ptr [rbx + r9*8 + 4], r8d
	test edi, edi
	jnz 5b
.Lrd_tdone:
	mov dword ptr [rbx + r14*8], eax
	mov dword ptr [rbx + r14*8 + 4], ecx
	add esi, edx
	mov dword ptr [r12+V_SIZE], esi
	pop r14
	pop r13
	pop r12
	pop rbp
	pop rbx
	ret

# ---------------------------------------------------------------------------
# p_copy_version(edi = source index) -> eax = new index or -1
# ---------------------------------------------------------------------------
p_copy_version:
	mov eax, dword ptr [r15+C_NV]
	cmp eax, MAXVERS
	jae .Lcv_fail
	mov ecx, eax
	shl ecx, 5
	lea r8, [r15 + C_VERS + rcx]        # dest
	shl edi, 5
	lea r9, [r15 + C_VERS + rdi]        # src
	mov esi, dword ptr [r9+V_SIZE]
	mov ecx, esi                        # copying costs one work unit per 16 entries
	shr ecx, 4
	sub qword ptr [r15+C_STEPS], rcx
	jb p_limit
	cmp esi, dword ptr [r8+V_CAP]
	jbe 1f
	mov rdi, r8
	call p_grow_vstack
1:	push rsi
	push rdi
	mov rdi, qword ptr [r8+V_E]
	mov rsi, qword ptr [r9+V_E]
	mov ecx, dword ptr [r9+V_SIZE]
	rep movsq
	pop rdi
	pop rsi
	mov ecx, dword ptr [r9+V_SIZE]
	mov dword ptr [r8+V_SIZE], ecx
	mov dword ptr [r8+V_STATUS], 0
	mov ecx, dword ptr [r9+V_DYN]
	mov dword ptr [r8+V_DYN], ecx
	mov ecx, dword ptr [r9+V_GID]
	mov dword ptr [r8+V_GID], ecx
	mov dword ptr [r8+V_NGID], 0
	inc dword ptr [r15+C_NV]
	ret
.Lcv_fail:
	mov dword ptr [r15+C_CAPHIT], 1
	mov eax, -1
	ret

# p_remove_version(edi = index): rotate the version (and its buffer) to the end, nv--
p_remove_version:
	mov eax, dword ptr [r15+C_NV]
	dec eax
	mov dword ptr [r15+C_NV], eax
	shl edi, 5
	lea r8, [r15 + C_VERS + rdi]
	movdqu xmm0, xmmword ptr [r8]
	movdqu xmm1, xmmword ptr [r8+16]
	shl eax, 5
	lea r9, [r15 + C_VERS + rax]        # last slot
1:	cmp r8, r9
	jae 2f
	movdqu xmm2, xmmword ptr [r8+32]
	movdqu xmm3, xmmword ptr [r8+48]
	movdqu xmmword ptr [r8], xmm2
	movdqu xmmword ptr [r8+16], xmm3
	add r8, 32
	jmp 1b
2:	movdqu xmmword ptr [r9], xmm0
	movdqu xmmword ptr [r9+16], xmm1
	ret

# p_swap_versions(edi, esi)
p_swap_versions:
	shl edi, 5
	shl esi, 5
	lea r8, [r15 + C_VERS + rdi]
	lea r9, [r15 + C_VERS + rsi]
	movdqu xmm0, xmmword ptr [r8]
	movdqu xmm1, xmmword ptr [r8+16]
	movdqu xmm2, xmmword ptr [r9]
	movdqu xmm3, xmmword ptr [r9+16]
	movdqu xmmword ptr [r9], xmm0
	movdqu xmmword ptr [r9+16], xmm1
	movdqu xmmword ptr [r8], xmm2
	movdqu xmmword ptr [r8+16], xmm3
	ret

# p_vpos(rdi = version ptr) -> eax = byte position (end of top node)
.macro VPOS vreg, o64, o32, tmp
	mov \o32, dword ptr [\vreg+V_SIZE]
	mov \tmp, qword ptr [\vreg+V_E]
	mov \o32, dword ptr [\tmp + \o64*8 - 8]
	shl \o64, 5
	mov \tmp, qword ptr [r15+C_NODES]
	mov \o32, dword ptr [\tmp + \o64 + N_END]
.endm

# ---------------------------------------------------------------------------
# p_subtree_compare(edi = a, esi = b) -> eax in {-1, 0, 1}
# ts_subtree_compare: pre-order comparison of (symbol, child count). Iterative over the frame
# stack so deep trees cannot overflow the native stack; each visited pair costs one work unit.
# ---------------------------------------------------------------------------
p_subtree_compare:
	push rbx
	push rbp
	push r12
	push r13
	push r14
	mov r12d, edi
	mov r13d, esi
	mov r8, qword ptr [r15+C_NODES]
	mov r9, qword ptr [r15+C_KIDS]
	mov rbx, qword ptr [r15+C_ESTK]
	xor ebp, ebp                        # frames on the stack
	jmp .Lsc_visit
.Lsc_loop:
	test ebp, ebp
	jz .Lsc_eq
	dec ebp
	mov eax, ebp
	shl eax, 4
	mov r12d, dword ptr [rbx + rax]
	mov r13d, dword ptr [rbx + rax + 4]
.Lsc_visit:
	sub qword ptr [r15+C_STEPS], 1
	jb p_limit
	mov eax, r12d
	shl rax, 5
	lea r10, [r8 + rax]
	mov eax, r13d
	shl rax, 5
	lea r11, [r8 + rax]
	movzx eax, word ptr [r10+N_SYM]
	movzx ecx, word ptr [r11+N_SYM]
	cmp eax, ecx
	jb .Lsc_m1
	ja .Lsc_p1
	mov ecx, dword ptr [r10+N_CC]
	cmp ecx, dword ptr [r11+N_CC]
	jb .Lsc_m1
	ja .Lsc_p1
	test ecx, ecx
	jz .Lsc_loop
	lea esi, [rbp + rcx]
	cmp esi, dword ptr [r15+C_ESTKCAP]
	jbe 1f
	call p_grow_estk
	mov rbx, qword ptr [r15+C_ESTK]
1:	mov edi, dword ptr [r10+N_CI]
	mov edx, dword ptr [r11+N_CI]
2:	dec ecx                             # push child pairs last-first so child 0 pops first
	mov r14d, ebp
	shl r14d, 4
	lea eax, [rdi + rcx]
	mov eax, dword ptr [r9 + rax*4]
	mov dword ptr [rbx + r14], eax
	lea eax, [rdx + rcx]
	mov eax, dword ptr [r9 + rax*4]
	mov dword ptr [rbx + r14 + 4], eax
	inc ebp
	test ecx, ecx
	jnz 2b
	jmp .Lsc_loop
.Lsc_eq:
	xor eax, eax
	jmp .Lsc_ret
.Lsc_m1:
	mov eax, -1
	jmp .Lsc_ret
.Lsc_p1:
	mov eax, 1
.Lsc_ret:
	pop r14
	pop r13
	pop r12
	pop rbp
	pop rbx
	ret

# p_equivalent(edi = a, esi = b) -> eax (same symbol, span, child count, extra)
p_equivalent:
	mov r8, qword ptr [r15+C_NODES]
	shl rdi, 5
	shl rsi, 5
	xor eax, eax
	mov ecx, dword ptr [r8 + rdi + N_SYM]
	and ecx, 0xFF00FFFF                 # symbol + extra (ignore production id)
	mov edx, dword ptr [r8 + rsi + N_SYM]
	and edx, 0xFF00FFFF
	cmp ecx, edx
	jne 1f
	mov rcx, qword ptr [r8 + rdi + N_START]
	cmp rcx, qword ptr [r8 + rsi + N_START]
	jne 1f
	mov ecx, dword ptr [r8 + rdi + N_CC]
	cmp ecx, dword ptr [r8 + rsi + N_CC]
	jne 1f
	mov eax, 1
1:	ret

# ---------------------------------------------------------------------------
# p_try_converge(edi = j, esi = i) -> eax 1 if converged (caller removes i), else 0
# ---------------------------------------------------------------------------
p_try_converge:
	push rbx
	push rbp
	push r12
	push r13
	push r14
	shl edi, 5
	lea r12, [r15 + C_VERS + rdi]       # X
	shl esi, 5
	lea r13, [r15 + C_VERS + rsi]       # Y
	xor eax, eax
	mov ecx, dword ptr [r12+V_SIZE]
	cmp ecx, dword ptr [r13+V_SIZE]
	jne .Ltc_ret
	mov r8, qword ptr [r12+V_E]
	mov r9, qword ptr [r13+V_E]
	lea ebp, [rcx-1]                    # hi
	mov ebx, ebp                        # k
	xor r14d, r14d                      # lo, the lowest differing entry (0: none)
	mov r10d, dword ptr [r12+V_GID]     # a group shares entries above its ambiguity, so scan past
	cmp r10d, dword ptr [r13+V_GID]     # them; other versions share only their common prefix
	sete r11b
	test r10d, r10d
	setnz r10b
	and r10b, r11b
.Ltc_scan:
	test ebx, ebx
	jz .Ltc_scanned
	mov edx, dword ptr [r8 + rbx*8]
	cmp edx, dword ptr [r9 + rbx*8]
	jne .Ltc_diff
	test r10b, r10b
	jz .Ltc_scanned
	dec ebx
	jmp .Ltc_scan
.Ltc_diff:
	mov edx, dword ptr [r8 + rbx*8 + 4]
	cmp edx, dword ptr [r9 + rbx*8 + 4]
	jne .Ltc_ret                        # eax = 0
	mov r14d, ebx
	dec ebx
	jmp .Ltc_scan
.Ltc_scanned:
	mov eax, ebp                        # the scan costs one work unit per 16 entries
	sub eax, ebx
	shr eax, 4
	sub qword ptr [r15+C_STEPS], rax
	jb p_limit
	mov eax, 1
	test r14d, r14d
	jz .Ltc_ret                         # identical
	mov ebx, r14d
	lea r14d, [rbx+1]
.Ltc_eq:
	cmp r14d, ebp
	ja .Ltc_pick
	mov r8, qword ptr [r12+V_E]
	mov r9, qword ptr [r13+V_E]
	mov edi, dword ptr [r8 + r14*8]
	mov esi, dword ptr [r9 + r14*8]
	call p_equivalent
	test eax, eax
	jz .Ltc_ret
	inc r14d
	jmp .Ltc_eq
.Ltc_pick:
	mov r8, qword ptr [r12+V_E]
	mov r9, qword ptr [r13+V_E]
	mov edi, dword ptr [r8 + rbx*8]     # xn
	mov esi, dword ptr [r9 + rbx*8]     # yn
	mov r10, qword ptr [r15+C_NODES]
	mov eax, edi
	shl rax, 5
	mov ecx, dword ptr [r10 + rax + N_DYN]
	mov eax, esi
	shl rax, 5
	mov edx, dword ptr [r10 + rax + N_DYN]
	cmp edx, ecx
	jg .Ltc_ywins
	jl .Ltc_xwins
	mov eax, dword ptr [r12+V_GID]      # same group: C kept both links and picked at a reduce
	test eax, eax                       # by compare; otherwise its merge drops Y's equivalent link
	jz 1f
	cmp eax, dword ptr [r13+V_GID]
	je 2f
1:	push rdi
	push rsi
	call p_equivalent
	pop rsi
	pop rdi
	test eax, eax
	jnz .Ltc_xwins
2:	call p_subtree_compare
	cmp eax, 0
	jle .Ltc_xwins
.Ltc_ywins:
	mov r8, qword ptr [r12+V_E]
	mov r9, qword ptr [r13+V_E]
	mov r10, qword ptr [r15+C_NODES]
	mov eax, dword ptr [r8 + rbx*8]
	shl rax, 5
	mov ecx, dword ptr [r10 + rax + N_DYN]
	sub dword ptr [r12+V_DYN], ecx
	mov rax, qword ptr [r9 + rbx*8]
	mov qword ptr [r8 + rbx*8], rax
	mov eax, eax
	shl rax, 5
	mov ecx, dword ptr [r10 + rax + N_DYN]
	add dword ptr [r12+V_DYN], ecx
.Ltc_xwins:
	mov eax, 1
.Ltc_ret:
	pop r14
	pop r13
	pop r12
	pop rbp
	pop rbx
	ret

# ---------------------------------------------------------------------------
# p_accept(edi = version index): build root, select against finished tree
# ---------------------------------------------------------------------------
p_accept:
	push rbx
	push rbp
	push r12
	push r13
	push r14
	shl edi, 5
	lea r12, [r15 + C_VERS + rdi]
	# push eof leaf (symbol 0, extra) with state 1
	mov rdi, r12
	mov esi, 1
	xor edx, edx
	mov ecx, 1
	call p_shift
	mov rbx, qword ptr [r12+V_E]
	mov ecx, dword ptr [r12+V_SIZE]
	# find topmost non-extra entry r (>= 1)
	lea ebp, [rcx-1]
1:	test byte ptr [rbx + rbp*8 + 6], 1
	jz 2f
	dec ebp
	jnz 1b
	ud2                                 # no root (cannot happen)
2:	mov r13d, dword ptr [rbx + rbp*8]   # root node index
	# total children = (size - 1) - 1 + root.cc
	mov r8, qword ptr [r15+C_NODES]
	mov eax, r13d
	shl rax, 5
	mov r14d, dword ptr [r8 + rax + N_CC]
	lea edi, [rcx - 2 + r14]
	mov eax, dword ptr [r15+C_NK]
	add eax, edi
	cmp eax, dword ptr [r15+C_KCAP]
	jbe 3f
	call p_grow_kids
3:	ALLOC_NODE eax
	push rax
	push rax
	mov r8, qword ptr [r15+C_NODES]
	mov ecx, r13d
	shl rcx, 5
	mov r9d, eax
	shl r9, 5
	movdqu xmm0, xmmword ptr [r8 + rcx]
	movdqu xmm1, xmmword ptr [r8 + rcx + 16]
	movdqu xmmword ptr [r8 + r9], xmm0
	movdqu xmmword ptr [r8 + r9 + 16], xmm1
	add r9, r8                          # new root ptr
	add rcx, r8                         # old root ptr
	mov r10, qword ptr [r15+C_KIDS]
	mov r11d, dword ptr [r15+C_NK]
	mov dword ptr [r9+N_CI], r11d
	mov esi, r11d                       # first child slot
	mov edx, 1                          # k
4:	cmp edx, dword ptr [r12+V_SIZE]
	jae 6f
	cmp edx, ebp
	jne 5f
	# splice root's children
	mov edi, dword ptr [rcx+N_CI]
	mov eax, r14d
	test eax, eax
	jz 7f
8:	mov r8d, dword ptr [r10 + rdi*4]
	mov dword ptr [r10 + r11*4], r8d
	inc edi
	inc r11d
	dec eax
	jnz 8b
7:	inc edx
	jmp 4b
5:	mov eax, dword ptr [rbx + rdx*8]
	mov dword ptr [r10 + r11*4], eax
	inc r11d
	inc edx
	jmp 4b
6:	mov eax, r11d
	sub eax, esi
	mov dword ptr [r9+N_CC], eax
	mov dword ptr [r15+C_NK], r11d
	mov r8, qword ptr [r15+C_NODES]
	mov eax, dword ptr [r10 + rsi*4]
	shl rax, 5
	mov eax, dword ptr [r8 + rax + N_START]
	mov dword ptr [r9+N_START], eax
	mov eax, dword ptr [r10 + r11*4 - 4]
	shl rax, 5
	mov eax, dword ptr [r8 + rax + N_END]
	mov dword ptr [r9+N_END], eax
	pop rax
	pop rax
	# select against finished
	mov ecx, dword ptr [r15+C_FINISHED]
	test ecx, ecx
	js .Lac_take
	mov edx, ecx
	shl rdx, 5
	mov edx, dword ptr [r8 + rdx + N_DYN]
	mov esi, dword ptr [r9+N_DYN]
	cmp esi, edx
	jg .Lac_take
	jl .Lac_done
	mov ebx, eax
	mov edi, ecx
	mov esi, eax
	call p_subtree_compare
	cmp eax, 0
	jle .Lac_done
	mov eax, ebx
.Lac_take:
	mov dword ptr [r15+C_FINISHED], eax
.Lac_done:
	mov dword ptr [r12+V_STATUS], 2
	pop r14
	pop r13
	pop r12
	pop rbp
	pop rbx
	ret

# ---------------------------------------------------------------------------
# p_advance(edi = version index): lex (or reuse cached token), apply actions until a shift,
# accept or error.  Mirrors ts_parser__advance.
# ---------------------------------------------------------------------------
	.p2align 4
p_advance:
	push rbx
	push rbp
	push r12
	push r13
	push r14
	sub rsp, 16                         # [rsp] = k, [rsp+4] = count, [rsp+8] = last_red
	sub qword ptr [r15+C_STEPS], 1
	jb p_limit
	mov ebx, edi
	mov eax, edi
	shl eax, 5
	lea r12, [r15 + C_VERS + rax]
	mov ecx, dword ptr [r12+V_SIZE]
	mov rdx, qword ptr [r12+V_E]
	movzx r13d, word ptr [rdx + rcx*8 - 4]      # state
	VPOS r12, rsi, esi, rdx
	cmp dword ptr [r15+C_TOKVALID], 0
	je .Lad_lex
	cmp esi, dword ptr [r15+C_TPOS]
	jne .Lad_lex
	mov edi, r13d
	push rsi
	push rsi
	call p_can_reuse
	pop rsi
	pop rsi
	test eax, eax
	jnz .Lad_have
.Lad_lex:
	mov edi, r13d
	call p_lex
	test eax, eax
	jz .Lad_dead
.Lad_have:
	mov r14d, dword ptr [r15+C_TSYM]
.Lad_lookup:
	mov eax, r13d
	imul eax, dword ptr [r15+C_LANG+L_NSYM]
	add eax, r14d
	mov rdx, qword ptr [r15+C_LANG+L_PARSE_TABLE]
	movzx ebp, word ptr [rdx + rax*2]   # action index
.Lad_entry:
	mov rdx, qword ptr [r15+C_LANG+L_ACTIONS]
	mov rax, qword ptr [rdx + rbp*8]
	movzx ecx, al                       # count
	cmp ecx, 1
	jne .Lad_multi
	# ---- single action fast path
	mov rsi, qword ptr [rdx + rbp*8 + 8]
	test esi, 3
	jnz .Lad_single_nonshift
	# shift
	mov ecx, esi
	shr ecx, 2
	and ecx, 1
	mov eax, esi
	shr eax, 16
	test ecx, ecx
	cmovnz eax, r13d
	mov rdi, r12
	mov esi, eax
	mov edx, r14d
	call p_shift
	jmp .Lad_ret
.Lad_single_nonshift:
	mov eax, esi
	and eax, 3
	cmp eax, 1
	jne .Lad_acc_or_rec
	mov rdi, r12
	call p_reduce
	mov ecx, dword ptr [r12+V_SIZE]
	mov rdx, qword ptr [r12+V_E]
	movzx r13d, word ptr [rdx + rcx*8 - 4]
	jmp .Lad_lookup
.Lad_acc_or_rec:
	cmp eax, 2
	jne .Lad_dead
	mov edi, ebx
	call p_accept
	jmp .Lad_ret
	# ---- zero or multiple actions
.Lad_multi:
	test ecx, ecx
	jz .Lad_noaction
	mov dword ptr [rsp+4], ecx
	mov dword ptr [rsp], 0
	mov dword ptr [rsp+8], -1
.Lad_mloop:
	mov ecx, dword ptr [rsp]
	cmp ecx, dword ptr [rsp+4]
	jae .Lad_mdone
	inc dword ptr [rsp]
	mov rdx, qword ptr [r15+C_LANG+L_ACTIONS]
	lea eax, [rbp + rcx + 1]
	mov rsi, qword ptr [rdx + rax*8]
	mov eax, esi
	and eax, 3
	jz .Lad_mshift
	cmp eax, 1
	jne .Lad_macc
	# reduce on a copy
	push rsi
	push rsi
	mov edi, ebx
	call p_copy_version
	pop rsi
	pop rsi
	test eax, eax
	js .Lad_dead
	mov ecx, eax                        # a fork of a group by action k: the same C version as
	shl ecx, 5                          # the other members' k-th forks, so derive the id from k
	mov edx, dword ptr [r15 + C_VERS + rcx + V_GID]
	test edx, edx
	jz 1f
	imul edx, edx, -1640531535
	add edx, dword ptr [rsp]
	or edx, 1
	mov dword ptr [r15 + C_VERS + rcx + V_GID], edx
1:	mov dword ptr [rsp+8], eax
	shl eax, 5
	lea rdi, [r15 + C_VERS + rax]
	call p_reduce
	jmp .Lad_mloop
.Lad_mshift:
	mov ecx, esi
	shr ecx, 2
	and ecx, 1
	mov eax, esi
	shr eax, 16
	test ecx, ecx
	cmovnz eax, r13d
	mov rdi, r12
	mov esi, eax
	mov edx, r14d
	call p_shift
	jmp .Lad_ret
.Lad_macc:
	cmp eax, 2
	jne .Lad_dead
	mov edi, ebx
	call p_accept
	jmp .Lad_ret
.Lad_mdone:
	mov eax, dword ptr [rsp+8]
	test eax, eax
	js .Lad_noaction
	# renumber: last reduction version replaces version ebx
	mov edi, ebx
	mov esi, eax
	call p_swap_versions
	mov edi, dword ptr [rsp+8]
	call p_remove_version
	mov ecx, dword ptr [r12+V_SIZE]
	mov rdx, qword ptr [r12+V_E]
	movzx r13d, word ptr [rdx + rcx*8 - 4]
	jmp .Lad_lookup
.Lad_noaction:
	# keyword -> word token fallback
	cmp dword ptr [r15+C_TKW], 0
	je .Lad_dead
	cmp r14d, dword ptr [r15+C_LANG+L_WORD]
	je .Lad_dead
	mov rdx, qword ptr [r15+C_LANG+L_RESERVED_SET]
	movzx eax, byte ptr [rdx + r13]
	imul eax, dword ptr [r15+C_LANG+L_RWORDS]
	mov edx, r14d
	shr edx, 6
	add eax, edx
	mov rdx, qword ptr [r15+C_LANG+L_RESERVED_BITS]
	mov rax, qword ptr [rdx + rax*8]
	bt rax, r14
	jc .Lad_dead
	mov eax, r13d
	imul eax, dword ptr [r15+C_LANG+L_NSYM]
	add eax, dword ptr [r15+C_LANG+L_WORD]
	mov rdx, qword ptr [r15+C_LANG+L_PARSE_TABLE]
	movzx eax, word ptr [rdx + rax*2]
	mov rdx, qword ptr [r15+C_LANG+L_ACTIONS]
	cmp byte ptr [rdx + rax*8], 0
	je .Lad_dead
	mov r14d, dword ptr [r15+C_LANG+L_WORD]
	mov ebp, eax
	jmp .Lad_entry
.Lad_dead:
	mov dword ptr [r12+V_STATUS], 1
.Lad_ret:
	add rsp, 16
	pop r14
	pop r13
	pop r12
	pop rbp
	pop rbx
	ret

# ---------------------------------------------------------------------------
# p_emit() -> rax = node count, nodes in the context's output buffer
# ---------------------------------------------------------------------------
p_emit:
	push rbx
	push rbp
	push r12
	push r13
	push r14
	mov esi, 1                          # the root; the rest grows as nodes are emitted
	cmp esi, dword ptr [r15+C_OUTCAP]
	jbe 1f
	lea rdi, [r15+C_OUT]
	mov ecx, 4
	call p_grow
1:	mov r8, qword ptr [r15+C_NODES]
	mov r12, qword ptr [r15+C_OUT]
	mov ecx, dword ptr [r15+C_FINISHED]
	mov eax, ecx
	shl rax, 5
	lea r9, [r8 + rax]
	mov r13, qword ptr [r15+C_LANG+L_SYMBOL_OUT]
	movzx eax, word ptr [r9+N_SYM]
	mov eax, dword ptr [r13 + rax*4]
	btr eax, 31
	mov dword ptr [r12], eax
	mov rax, qword ptr [r9+N_START]
	mov qword ptr [r12+4], rax
	mov dword ptr [r12+12], -1
	mov r14d, 1                         # n
	# frame stack
	cmp dword ptr [r15+C_ESTKCAP], 0
	jne 2f
	mov esi, 1
	call p_grow_estk
2:	mov rbx, qword ptr [r15+C_ESTK]
	xor ebp, ebp                        # sp (frames)
	mov dword ptr [rbx], ecx
	mov qword ptr [rbx+4], 0
	mov dword ptr [rbx+12], 0
	inc ebp
	mov r10, qword ptr [r15+C_KIDS]
	mov r8, qword ptr [r15+C_NODES]
.Lem_loop:
	test ebp, ebp
	jz .Lem_done
	mov eax, ebp
	shl eax, 4
	lea rdi, [rbx + rax - 16]           # frame ptr
	mov eax, dword ptr [rdi]
	shl rax, 5
	lea r9, [r8 + rax]                  # parent node
	mov ecx, dword ptr [rdi+4]          # ci
	cmp ecx, dword ptr [r9+N_CC]
	jae .Lem_pop
	lea edx, [rcx+1]
	mov dword ptr [rdi+4], edx
	add ecx, dword ptr [r9+N_CI]
	mov esi, dword ptr [r10 + rcx*4]    # child index
	mov eax, esi
	shl rax, 5
	lea r11, [r8 + rax]                 # child node
	xor edx, edx                        # alias
	cmp byte ptr [r11+N_EXTRA], 0
	jne 2f
	movzx eax, byte ptr [r9+N_PROD]
	shl eax, 4
	add eax, dword ptr [rdi+8]
	inc dword ptr [rdi+8]
	mov rcx, qword ptr [r15+C_LANG+L_ALIAS_SEQ]
	movzx edx, word ptr [rcx + rax*2]
2:	movzx eax, word ptr [r11+N_SYM]
	test edx, edx
	cmovnz eax, edx                     # s
	mov eax, dword ptr [r13 + rax*4]    # output word, visible in bit 31
	mov r9d, dword ptr [rdi+12]         # parent out index
	btr eax, 31
	jc 3f
	test edx, edx                       # an aliased node is visible
	jz 4f
3:	cmp r14d, dword ptr [r15+C_OUTCAP]
	jae .Lem_grow
.Lem_put:
	mov rdx, r14
	shl rdx, 4
	add rdx, r12
	mov dword ptr [rdx], eax
	mov rax, qword ptr [r11+N_START]
	mov qword ptr [rdx+4], rax
	mov dword ptr [rdx+12], r9d
	mov r9d, r14d
	inc r14
4:	cmp dword ptr [r11+N_CC], 0
	je .Lem_loop
	# push frame (child, 0, 0, parent)
	lea eax, [rbp+1]
	cmp eax, dword ptr [r15+C_ESTKCAP]
	jb 5f
	push rsi
	mov esi, eax
	call p_grow_estk
	pop rsi
	mov rbx, qword ptr [r15+C_ESTK]
5:	mov eax, ebp
	shl eax, 4
	mov dword ptr [rbx + rax], esi
	mov qword ptr [rbx + rax + 4], 0
	mov dword ptr [rbx + rax + 12], r9d
	inc ebp
	jmp .Lem_loop
.Lem_pop:
	dec ebp
	jmp .Lem_loop
.Lem_done:
	mov rax, r14
	jmp .Lem_ret
.Lem_grow:
	push rdi
	push rsi
	lea rdi, [r15+C_OUT]
	lea esi, [r14+1]
	mov ecx, 4
	call p_grow
	pop rsi
	pop rdi
	mov r12, qword ptr [r15+C_OUT]
	jmp .Lem_put
.Lem_ret:
	pop r14
	pop r13
	pop r12
	pop rbp
	pop rbx
	ret

# ---------------------------------------------------------------------------
# int64_t tsasm_parse(TsasmParser *p, const TsasmLanguage *lang, const uint8_t *src, uint64_t len,
#                     const TsasmNode **nodes)
# ---------------------------------------------------------------------------
	.globl tsasm_parse
	.type tsasm_parse, @function
	.p2align 4
tsasm_parse:
	push rbx
	push rbp
	push r12
	push r13
	push r14
	push r15
	sub rsp, 8
	mov r15, rdi
	mov qword ptr [r15+C_SAVEDRSP], rsp
	mov qword ptr [r15+C_RESULT], r8
	.irp off, 0, 16, 32, 48, 64, 80, 96, 112
	movdqu xmm0, xmmword ptr [rsi + \off]
	movdqu xmmword ptr [r15 + C_LANG + \off], xmm0
	.endr
	mov rsi, rdx
	mov rdx, rcx
	mov rax, rdx                        # keep buffers up to max(limit / 8, 256 * len): a big input
	shl rax, RETAIN_SHIFT               # reuses what the last big input grew, and a small one
	mov r8, qword ptr [r15+C_MEMLIMIT]  # drops it (a wrapped shift only frees early)
	shr r8, RETAIN_LIMIT_SHIFT
	cmp rax, r8
	cmovb rax, r8
	cmp qword ptr [r15+C_MEMUSED], rax
	jbe 1f
	push rsi
	push rdx
	call p_release
	pop rdx
	pop rsi
1:	mov rdi, rsi
	mov rsi, rdx
	mov rax, rsi
	shl rax, 6
	add rax, 10000
	mov qword ptr [r15+C_STEPS], rax    # advance budget: 64 * len + 10000
	mov rax, rsi
	shl rax, 5
	add rax, 100000
	mov r8d, 0x7FFFFFF
	cmp rax, r8
	cmova rax, r8
	mov dword ptr [r15+C_NODELIM], eax  # node budget: 32 * len + 100000
	call p_set_navail
	mov rax, ERR_LIMIT
	mov r8d, 0xFFFFFFF0                 # byte offsets are 32-bit: reject inputs >= ~4 GiB
	cmp rsi, r8
	jae .Lmain_ret
	mov qword ptr [r15+C_SRC], rdi
	add rsi, rdi
	mov qword ptr [r15+C_END], rsi
	mov dword ptr [r15+C_NN], 0
	mov dword ptr [r15+C_NK], 0
	mov dword ptr [r15+C_FINISHED], -1
	mov dword ptr [r15+C_TOKVALID], 0
	mov dword ptr [r15+C_LASTPOS], 0
	mov dword ptr [r15+C_CAPHIT], 0
	mov qword ptr [r15+C_NEXTGID], 0    # and C_GLIVE
	# node 0: zeroed stack-base node
	ALLOC_NODE eax
	mov r8, qword ptr [r15+C_NODES]
	pxor xmm0, xmm0
	movdqu xmmword ptr [r8], xmm0
	movdqu xmmword ptr [r8+16], xmm0
	# version 0: base entry (node 0, state 1)
	mov dword ptr [r15+C_NV], 1
	lea r12, [r15 + C_VERS]
	mov dword ptr [r12+V_STATUS], 0
	mov dword ptr [r12+V_DYN], 0
	mov qword ptr [r12+V_GID], 0        # and V_NGID
	cmp dword ptr [r12+V_CAP], 0
	jne 1f
	mov rdi, r12
	mov esi, 256
	call p_grow_vstack
1:	mov rax, qword ptr [r12+V_E]
	mov dword ptr [rax], 0
	mov dword ptr [rax+4], 1
	mov dword ptr [r12+V_SIZE], 1

.Lmain_outer:
.ifdef DEBUG
	mov rdi, r15
	call tsasm_dbg@PLT
.endif
	cmp dword ptr [r15+C_NV], 0
	je .Lmain_end
	xor ebx, ebx                        # vi
.Lmain_vloop:
	cmp ebx, dword ptr [r15+C_NV]
	jae .Lmain_condense
	mov eax, ebx
	shl eax, 5
	lea r12, [r15 + C_VERS + rax]
.Lmain_adv:
	cmp dword ptr [r12+V_STATUS], 0
	jne .Lmain_vnext
	mov edi, ebx
	call p_advance
	cmp dword ptr [r12+V_STATUS], 0
	jne .Lmain_vnext
	VPOS r12, rax, eax, rdx
	mov ecx, dword ptr [r15+C_LASTPOS]
	cmp eax, ecx
	ja .Lmain_newpos
	jb .Lmain_adv
	test ebx, ebx
	jz .Lmain_adv
.Lmain_newpos:
	mov dword ptr [r15+C_LASTPOS], eax
	cmp dword ptr [r15+C_NV], 1         # single version: keep going without condensing
	je .Lmain_adv
.Lmain_vnext:
	inc ebx
	jmp .Lmain_vloop

.Lmain_condense:
	xor ebx, ebx                        # i
.Lcd_i:
	cmp ebx, dword ptr [r15+C_NV]
	jae .Lcd_cap
	sub qword ptr [r15+C_STEPS], 1      # a unit per version condensed: the pair loop is
	jb p_limit                          # at most MAXVERS / 2 compares per unit
	mov eax, ebx
	shl eax, 5
	lea r12, [r15 + C_VERS + rax]
	cmp dword ptr [r12+V_STATUS], 0
	je .Lcd_live
	mov edi, ebx
	call p_remove_version
	jmp .Lcd_i
.Lcd_live:
	xor ebp, ebp                        # j
.Lcd_j:
	cmp ebp, ebx
	jae .Lcd_inext
	mov eax, ebp
	shl eax, 5
	lea r13, [r15 + C_VERS + rax]       # X = j
	# same state?
	mov ecx, dword ptr [r12+V_SIZE]
	mov rdx, qword ptr [r12+V_E]
	movzx ecx, word ptr [rdx + rcx*8 - 4]
	mov esi, dword ptr [r13+V_SIZE]
	mov rdx, qword ptr [r13+V_E]
	movzx esi, word ptr [rdx + rsi*8 - 4]
	cmp ecx, esi
	jne .Lcd_dyn
	VPOS r12, rax, eax, rdx
	VPOS r13, rcx, ecx, rdx
	cmp eax, ecx
	jne .Lcd_dyn
	mov edi, ebp
	mov esi, ebx
	call p_try_converge
	test eax, eax
	jz .Lcd_group
	mov edi, ebx
	call p_remove_version
	jmp .Lcd_i                          # i now refers to the next version
.Lcd_dyn:
	mov eax, dword ptr [r12+V_DYN]
	cmp eax, dword ptr [r13+V_DYN]
	jle .Lcd_jnext
	mov edi, ebp
	mov esi, ebx
	call p_swap_versions
	jmp .Lcd_jnext
.Lcd_group:                             # C merges the heads anyway: X and Y form one group
	mov eax, dword ptr [r13+V_GID]      # only versions that were one head, or none, can join:
	cmp eax, dword ptr [r12+V_GID]      # C's links of separate heads cross in ways that lone
	jne .Lcd_jnext                      # versions do not represent
	mov eax, dword ptr [r13+V_NGID]
	test eax, eax
	jnz 1f
	add dword ptr [r15+C_NEXTGID], 2    # fresh ids are even, fork ids (p_advance) odd
	mov eax, dword ptr [r15+C_NEXTGID]
	mov dword ptr [r13+V_NGID], eax
1:	mov dword ptr [r12+V_NGID], eax
	or dword ptr [r15+C_GLIVE], 1
.Lcd_jnext:
	inc ebp
	jmp .Lcd_j
.Lcd_inext:
	inc ebx
	jmp .Lcd_i
.Lcd_cap:                               # groups not re-formed this condense have split
	mov eax, dword ptr [r15+C_GLIVE]
	test eax, eax                       # no group now or before: every id is already 0
	jz .Lcd_capcheck
	add eax, eax
	and eax, 2
	mov dword ptr [r15+C_GLIVE], eax
	mov ecx, dword ptr [r15+C_NV]
	lea r8, [r15 + C_VERS]
	jmp 2f
1:	mov eax, dword ptr [r8+V_NGID]
	mov dword ptr [r8+V_GID], eax
	mov dword ptr [r8+V_NGID], 0
	add r8, 32
	dec ecx
2:	test ecx, ecx
	jnz 1b
.Lcd_capcheck:
	cmp dword ptr [r15+C_NV], MAXV
	jbe .Lmain_outer
	mov dword ptr [r15+C_CAPHIT], 1
	mov edi, MAXV
	call p_remove_version
	jmp .Lcd_capcheck

.Lmain_end:
	cmp dword ptr [r15+C_FINISHED], 0
	jge 1f
	mov rax, ERR_SYNTAX
	cmp dword ptr [r15+C_CAPHIT], 0     # a version was dropped at the cap: not a proven error
	je .Lmain_ret
	mov rax, ERR_LIMIT
	jmp .Lmain_ret
1:	call p_emit
.Lmain_ret:
	mov rcx, qword ptr [r15+C_RESULT]
	test rcx, rcx
	jz 2f
	xor edx, edx
	test rax, rax
	cmovns rdx, qword ptr [r15+C_OUT]
	mov qword ptr [rcx], rdx
2:	add rsp, 8
	pop r15
	pop r14
	pop r13
	pop r12
	pop rbp
	pop rbx
	ret
	.size tsasm_parse, .-tsasm_parse

	.set C_ALLOC, (C_SIZE + 63) & ~63

# TsasmParser *tsasm_parser_new(void): zeroed, cache-line aligned context (NULL if out of memory)
	.globl tsasm_parser_new
	.type tsasm_parser_new, @function
tsasm_parser_new:
	push rbx
	mov edi, 64
	mov esi, C_ALLOC
	call aligned_alloc@PLT
	test rax, rax
	jz 1f
	mov rbx, rax
	mov rdi, rax
	xor eax, eax
	mov ecx, C_ALLOC
	rep stosb
	mov rax, rbx
	mov qword ptr [rax+C_MEMLIMIT], DEFAULT_MEMLIMIT
1:	pop rbx
	ret
	.size tsasm_parser_new, .-tsasm_parser_new

# void tsasm_parser_free(TsasmParser *p)
	.globl tsasm_parser_free
	.type tsasm_parser_free, @function
tsasm_parser_free:
	test rdi, rdi
	jz 1f
	push r15
	mov r15, rdi
	call p_release
	mov rdi, r15
	pop r15
	jmp free@PLT
1:	ret
	.size tsasm_parser_free, .-tsasm_parser_free

# void tsasm_parser_set_memory_limit(TsasmParser *p, uint64_t bytes)
	.globl tsasm_parser_set_memory_limit
	.type tsasm_parser_set_memory_limit, @function
tsasm_parser_set_memory_limit:
	mov qword ptr [rdi+C_MEMLIMIT], rsi
	cmp qword ptr [rdi+C_MEMUSED], rsi
	jbe 1f
	push r15
	mov r15, rdi
	call p_release
	pop r15
1:	ret
	.size tsasm_parser_set_memory_limit, .-tsasm_parser_set_memory_limit

# const char *tsasm_language_symbol_name(const TsasmLanguage *lang, uint16_t symbol)
	.globl tsasm_language_symbol_name
	.type tsasm_language_symbol_name, @function
tsasm_language_symbol_name:
	movzx esi, si
	lea rax, [rip + .Lempty]
	cmp esi, dword ptr [rdi+L_TOTAL_SYMS]
	jae 1f
	mov rax, qword ptr [rdi+L_SYMBOL_NAMES]
	mov rax, qword ptr [rax + rsi*8]
1:	ret
	.size tsasm_language_symbol_name, .-tsasm_language_symbol_name

